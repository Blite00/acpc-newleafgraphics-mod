"""Pack original seasonal New Leaf water resources; no painted substitutes."""
from pathlib import Path
from PIL import Image
import numpy as np
import json

ROOT=Path(__file__).resolve().parent
SRC=ROOT/'terrain_source'
CODE=ROOT/'ACGC-PC-Port'
def array(name,a):
    b=a.astype(np.uint8).tobytes()
    return 'static const unsigned char '+name+'[] = {\n'+''.join(','.join(map(str,b[i:i+32]))+',\n' for i in range(0,len(b),32))+'};\n'
out=['/* Generated by generate_water.py; original seasonal donor water textures. */\n']
textures=['tex_river','tex_river_n','tex_wave','tex_wave_nuki']
unique={}; refs=[]
for season in range(10):
    row=[]
    for name in textures:
        # One atlas cell is one full source period, including rectangular masks.
        p=SRC/f'grassA_season{season:02}'/(name+'.png')
        image=Image.open(p).convert('RGBA')
        if name=='tex_river_n':
            # HILO8 decoder correction: hardware RG=(raw byte1,byte0).
            # Ohana's PNG stores these in alpha and red, respectively.
            a=np.array(image)[:,:,[3,0,1,2]].copy(); a[:,:,2]=0; a[:,:,3]=255
            image=Image.fromarray(a)
        a=np.asarray(image.resize((128,128),Image.Resampling.BILINEAR))
        key=a.tobytes()
        if key not in unique:
            label=f'pc_water_image_{len(unique)}'; unique[key]=label
            out.append(array(label,a))
        row.append(unique[key])
    refs.append(row)
out.append('static const unsigned char* pc_water_images[10][4]={\n'+''.join('{'+','.join(row)+'},\n' for row in refs)+'};\n')
(CODE/'pc/src/pc_water_data.c_inc').write_text(''.join(out))
tables=json.loads((SRC/'lighting_lut_decoded.json').read_text())['tables']
shader=[]
for name in ['lu_field_water','lu_field_water_f']:
    table=next(t for t in tables if t['sampler']==name)
    assert table['absolute_input_flag']==1
    label='donorWaterLut' if name=='lu_field_water' else 'donorWaterFresnelLut'
    shader.append('const float '+label+'[256]=float[256](\n'+',\n'.join(','.join(f'{v:.8f}' for v in table['values'][i:i+8]) for i in range(0,256,8))+');\n')
(SRC/'water_lut_shader.txt').write_text(''.join(shader))
print(f'Packed {len(unique)} distinct original water cells for all ten seasonal sets; decoded water/Fresnel LUTs.')
