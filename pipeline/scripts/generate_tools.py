"""New Leaf 3D tools in the player's hand (axe, net, fishing rod, shovel, golden versions).

The New Leaf tool models share the GameCube tool frame (grip at the origin, handle along +z, head towards +x) at
1/120 scale, so every model is placed with a plain scale. Static tools (axe, shovel) replace the GC display list;
skeletal tools (net, rod) are split over the GC joints so the native swing, bend and net-sway animation still drive
them: each vertex goes to the joint that owns that part of the GC tool (by its New Leaf bone or position along the
rod), is stored in that joint's local frame (GC rest pose), and triangles that cross joints load the parent joint's
vertices with its matrix (anime_6_mdl[k]) exactly like the GC data does.
Writes ACGC-PC-Port/pc/src/pc_tools.c_inc and screens/tools/review_*.png.
"""
import json, sys
from pathlib import Path
import numpy as np
from PIL import Image
import ckf
import tool_common as tc
import tool_rend as tr

ROOT = Path(__file__).resolve().parent
PT = tc.MODEL/'player_tool.c'
OUT = ROOT/'ACGC-PC-Port/pc/src/pc_tools.c_inc'
SCALE = 120.0
ALPHA_TOOLS = {'net', 'g_net'}
WRAP = {0: 'GX_CLAMP', 1: 'GX_CLAMP', 2: 'GX_REPEAT', 3: 'GX_MIRROR'}

out = ['/* Generated by generate_tools.py: New Leaf tool models in the GC tool frames. */']
textures = {}
review = []


def rgba8(name, im):
    im = im.convert('RGBA'); w, h = im.size; data = bytearray()
    for ty in range(0, h, 4):
        for tx in range(0, w, 4):
            tile = [im.getpixel((tx+x, ty+y)) for y in range(4) for x in range(4)]
            data.extend(c for r, g, b, a in tile for c in (a, r)); data.extend(c for r, g, b, a in tile for c in (g, b))
    out.append(f'static u8 {name}[] ATTRIBUTE_ALIGN(32) = {{')
    out.extend(','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32))
    out.append('};')


def texture(tool, mesh):
    key = (tool, mesh['texture'])
    if key not in textures:
        name = f"pc_tool_{tool}_{mesh['texture']}_tex".replace('-', '_')
        im = Image.open(tc.SRC/tool/f"{mesh['texture']}.png").convert('RGBA')
        if tool not in ALPHA_TOOLS: im.putalpha(255)   # NL keeps gloss masks in alpha; only the net mesh is see-through
        rgba8(name, im); textures[key] = (name, im.size)
    return textures[key]


def smooth_normals(V):
    """the exported tool meshes carry no normals: area-weighted vertex normals, shared by equal positions"""
    P = np.array([v['position'] for v in V], float)
    acc = {}
    for i in range(0, len(V)-2, 3):
        n = np.cross(P[i+1]-P[i], P[i+2]-P[i])
        for k in range(3): acc.setdefault(tuple(np.round(P[i+k], 4)), np.zeros(3)).__iadd__(n)
    out = []
    for p in P:
        n = acc[tuple(np.round(p, 4))]; out.append(n/max(np.linalg.norm(n), 1e-9))
    return out


def nl_tris(tool, meshes, model=None):
    """[(mesh, [(pos, uv, normal, bone)]*3)] in GC tool units"""
    res = []
    for m in tc.nl_meshes(tool, model):
        mesh = m[0]
        if meshes is not None and id(mesh) and meshes(mesh) is False: continue
        V = mesh['vertices']; NS = smooth_normals(V)
        for i in range(0, len(V)-2, 3):
            tri = []
            for v, n in zip(V[i:i+3], NS[i:i+3]):
                tri.append((np.array(v['position'], float)*SCALE, (v['uv'][0], v['uv'][1]), n, v['nodes'][0] if v['nodes'] else 0))
            res.append((mesh, tri))
    return res


def emit_dl(name, tool, tris, assign, local, own, fmt_mtx=None):
    """tris: [(mesh, tri)]; assign(vertex)-> matrix index; local[k] = inverse rest matrix of matrix k (4x4)
    own: this DL's matrix index (None = static model). Writes Vtx + Gfx arrays."""
    by_tex = {}
    for mesh, tri in tris: by_tex.setdefault((mesh['texture'], WRAP[mesh['mapper']['wrapU']], WRAP[mesh['mapper']['wrapV']]), []).append((mesh, tri))
    vtx = []; gfx = [f'Gfx {name}[] = {{', 'gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),',
                     'gsDPSetPrimColor(0,128,255,255,255,255),',
                     'gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,0,0,0,COMBINED),',
                     'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_TEX_EDGE2),']
    for (texname, wu, wv), group in by_tex.items():
        tname, (tw, th) = texture(tool, group[0][0])
        gfx += [f'gsDPSetTextureImage_Dolphin(G_IM_FMT_RGBA,G_IM_SIZ_32b,{tw},{th},{tname}),',
                f'gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE,0,0,{wu},{wv},0,0),',
                'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_FOG|G_LIGHTING|G_SHADING_SMOOTH),']
        # batches of up to 10 triangles (30 vertices), vertices ordered by matrix
        for b in range(0, len(group), 10):
            batch = group[b:b+10]
            verts = []
            for mesh, tri in batch:
                # shift whole UV tiles into range by an even count: an odd shift flips a GX_MIRROR texture
                su = 2*np.floor(min(v[1][0] for v in tri)/2); sv = 2*np.floor(min(1-v[1][1] for v in tri)/2)
                for p, uv, n, bone in tri:
                    k = assign(p, bone)
                    verts.append((k, p, (uv[0]-su, (1-uv[1])-sv), n))
            order = sorted(range(len(verts)), key=lambda i: (verts[i][0] != own, verts[i][0]))
            slot = {i: pos for pos, i in enumerate(order)}
            # load runs per matrix
            runs = []
            for pos, i in enumerate(order):
                k = verts[i][0]
                if not runs or runs[-1][0] != k: runs.append([k, pos, 0])
                runs[-1][2] += 1
            base = len(vtx)
            for i in order:
                k, p, (u, v), n = verts[i]
                M = local[k]
                q = (M@np.append(p, 1.0))[:3]; nn = M[:3, :3]@n; nn /= max(np.linalg.norm(nn), 1e-9)
                nb = [int(round(c*127)) & 255 for c in nn]
                vtx.append('{{{%d,%d,%d},0,{%d,%d},{%d,%d,%d,255}}},' % (round(q[0]), round(q[1]), round(q[2]),
                           round(u*tw*32), round(v*th*32), nb[0], nb[1], nb[2]))
            cur = own
            for k, start, count in runs:
                if own is not None and k != cur:
                    gfx.append(f'gsSPMatrix(&anime_6_mdl[{k}],G_MTX_NOPUSH|G_MTX_LOAD|G_MTX_MODELVIEW),'); cur = k
                gfx.append(f'gsSPVertex(&{name}_v[{base+start}],{count},{start}),')
            if own is not None and cur != own:
                gfx.append(f'gsSPMatrix(&anime_6_mdl[{own}],G_MTX_NOPUSH|G_MTX_LOAD|G_MTX_MODELVIEW),')
            for t in range(len(batch)):
                gfx.append(f'gsSP1Triangle({slot[3*t]},{slot[3*t+1]},{slot[3*t+2]},0),')
    gfx += ['gsSPEndDisplayList(),', '};']
    out.append(f'static Vtx {name}_v[] ATTRIBUTE_ALIGN(32) = {{'); out.extend(vtx); out.append('};')
    out.extend(gfx)


static_swaps = []     # (native DL, new DL)
joint_swaps = []      # (joint table, index, new DL)


def static_tool(native, tool, keep_mesh=None, model=None):
    tris = nl_tris(tool, keep_mesh, model)
    name = f'pc_tool_{native}'
    emit_dl(name, tool, tris, lambda p, b: 0, [np.eye(4)], None)
    static_swaps.append((native, name))
    gc = tc.gc_dl(PT, native)
    nlg = [([[(p, uv, n) for p, uv, n, _ in t] for _, t in tris], Image.open(tc.SRC/tool/f"{tris[0][0]['texture']}.png"))]
    review.append((native, gc, nlg))


def skeletal_tool(skel, anim, tool, assign_joint, model=None, frame=0):
    """assign_joint(pos, bone) -> GC joint index (must have a model)"""
    jt = ckf.joints(PT, skel)
    a = ckf.Anim(PT, anim, len(jt)); rt, r = a.sample(frame); W = ckf.world(jt, rt, r)
    drawn = [i for i, j in enumerate(jt) if j[0]]
    mtx_of = {j: k for k, j in enumerate(drawn)}
    local = [np.linalg.inv(W[j]) for j in drawn]
    tris = nl_tris(tool, None, model)
    # each triangle goes to the deepest joint among its vertices (parents' matrices are already computed)
    per_joint = {j: [] for j in drawn}
    for mesh, tri in tris:
        js = [assign_joint(p, b) for p, _, _, b in tri]
        per_joint[max(js, key=lambda j: drawn.index(j))].append((mesh, tri))
    for j in drawn:
        name = f'pc_tool_{jt[j][0]}'
        emit_dl(name, tool, per_joint[j], lambda p, b: mtx_of[assign_joint(p, b)], local, mtx_of[j])
        joint_swaps.append((f'cKF_je_r_{skel}_tbl', j, name, jt[j][0]))
    gc, _, _ = tc.gc_skeleton_groups(PT, skel, a, frame)
    nlg = [([[(p, uv, n) for p, uv, n, _ in t] for _, t in tris], Image.open(tc.SRC/tool/f"{tris[0][0]['texture']}.png"))]
    review.append((skel, gc, nlg))


# axes: the New Leaf axe has three edge meshes (new, chipped, cracked) = the GC wear stages
def axe_mesh_filter(edge):
    state = {'i': -1}
    def f(mesh):
        state['i'] += 1
        return None if state['i'] in (0, edge) else False
    return f
static_tool('tol_axe_1_model', 'axe', axe_mesh_filter(1))
static_tool('tol_axe_1_b_model', 'axe', axe_mesh_filter(2))
static_tool('tol_axe_1_c_model', 'axe', axe_mesh_filter(3))
static_tool('tol_axe_2_model', 'g_axe')
static_tool('tol_scoop_1_model', 'scoop')
static_tool('tol_scoop_2_model', 'g_scoop')

# fishing rod: GC joints 1..4 start at z = 0, 1500, 3350, 4950 (straight rest pose of sao_swing1)
ROD_SPLIT = [(4950, 4), (3350, 3), (1500, 2)]
def rod_joint(p, bone):
    for z, j in ROD_SPLIT:
        if p[2] >= z: return j
    return 1
skeletal_tool('tol_sao_1', 'tol_sao_1_sao_swing1', 'pole', rod_joint)
skeletal_tool('tol_sao_2', 'tol_sao_1_sao_swing1', 'g_pole', rod_joint)

# net: New Leaf bones root/j1/j2 = handle and hoop -> e_net (joint 2); j3 = the bag -> main_net (4), its far end
# beyond the GC main2 joint (x < -2000 in the tool frame) -> main2_net (5)
def net_joint(p, bone):
    if bone < 3: return 2
    return 5 if p[0] < -2000 else 4
skeletal_tool('tol_net_1', 'tol_net_1_swing_wait1', 'net', net_joint)
skeletal_tool('tol_net_2', 'tol_net_1_swing_wait1', 'g_net', net_joint)

# umbrellas: the GC handle (e_umb) runs along +x from the hook (x ~ -800, bending to -z) to the tip, and the canopy
# (kasa_umb) is drawn 4500 further along x with its apex at its own origin and the rim at -x. The New Leaf umbrella
# stands along +z (hook bending to +x). Rotate (x,y,z) -> (z, y, -x) and put the New Leaf apex on the GC apex;
# canopy vertices are then stored relative to the canopy origin so the native open/close scaling still works.
UMB = {6: 'umb_petal', 7: 'umb_ribbon', 8: 'umb_ging_candy', 10: 'umb_lacy', 11: 'umb_elegant', 16: 'umb_sunny',
       17: 'umb_bat', 19: 'umb_ylw', 20: 'umb_leaf', 22: 'umb_paper', 23: 'umb_dot_toad', 25: 'umb_busted',
       31: 'umb_blu', 32: 'umb_flame'}
KASA_X = 4500.0
UMB_REVIEW = {}
for num, tool in UMB.items():
    f = tc.MODEL/f'tol_umb_{num:02d}.c'
    gk = tc.gc_dl(f, f'kasa_umb{num:02d}_model'); ge = tc.gc_dl(f, f'e_umb{num:02d}_model')
    gc_apex = tc.gc_points(gk)[:, 0].max()+KASA_X
    meshes = tc.nl_meshes(tool)
    cz = np.array([v['position'][2] for m, _ in meshes if not m['texture'].endswith('_0') for v in m['vertices']])*SCALE
    shift = gc_apex-cz.max()
    def place(p, shift=shift): return np.array([p[2]+shift, p[1], -p[0]])
    for part, keep in (('kasa', lambda t: not t.endswith('_0')), ('e', lambda t: t.endswith('_0'))):
        native = f'{part}_umb{num:02d}_model'
        tris = []
        for m, tex in meshes:
            if not keep(m['texture']): continue
            V = m['vertices']; NS = smooth_normals(V)
            for i in range(0, len(V)-2, 3):
                tri = []
                for v, n in zip(V[i:i+3], NS[i:i+3]):
                    pp = np.array(v['position'], float)*SCALE
                    n = np.array([n[2], n[1], -n[0]])
                    q = place(pp)
                    if part == 'kasa': q = q-[KASA_X, 0, 0]
                    tri.append((q, (v['uv'][0], v['uv'][1]), n, 0))
                tris.append((m, tri))
        if not tris: continue
        name = f'pc_tool_{native}'
        emit_dl(name, tool, tris, lambda p, b: 0, [np.eye(4)], None)
        static_swaps.append((native, name))
        tex_of = {m['texture']: t for m, t in meshes}
        off = np.array([KASA_X, 0, 0]) if part == 'kasa' else 0
        gsh = [([[(np.array(p)+[KASA_X, 0, 0], uv, n) for p, uv, n in t] for t in g], im) for g, im in gk]
        UMB_REVIEW.setdefault(num, [gsh+ge, []])[1].append(([[(p+off, uv, n) for p, uv, n, _ in t] for _, t in tris], tex_of[tris[0][0]['texture']]))
for num, (g, n) in UMB_REVIEW.items(): review.append((f'umb{num}', g, n))

out += ['', 'int g_pc_nl_tools = 1;']
out += [f'extern Gfx {a}[];' for a, _ in static_swaps]
out += ['Gfx* pc_tool_static_dl(Gfx* native) {', '    if (!g_pc_nl_tools || native == NULL) return native;']
out += [f'    if (native == {a}) return {b};' for a, b in static_swaps] + ['    return native;', '}']
tables = sorted({t for t, _, _, _ in joint_swaps})
out += [f'extern cKF_Joint_R_c {t}[];' for t in tables]
out += ['void pc_tool_patch_joints(void) {', '    if (!g_pc_nl_tools) return;']
out += [f'    {t}[{j}].model = {n};   /* was {old} */' for t, j, n, old in joint_swaps] + ['}']
OUT.write_text('\n'.join(out)+'\n')

