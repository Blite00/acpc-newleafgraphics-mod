def nbytes(n, bias=True):
    n = np.array(n, float); l = float(np.linalg.norm(n)) or 1.0; n = n/l
    if bias: n = n*0.3+np.array([0, 1.0, 0]); n = n/(float(np.linalg.norm(n)) or 1.0)
    return ','.join(str(int(round(c*126)) & 255) for c in n)

