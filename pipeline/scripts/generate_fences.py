def box(p0, p1, tangent, height0, height1, half_thick, rail_uv, offs=None):
    """Thin box along p0->p1 (model units)."""
    t = (p1-p0); L = np.linalg.norm(t); t /= L
    n = np.array([-t[1], t[0]])
    corners = []
    for e in ((p0, 0), (p1, 1)):
        for sgn in (-1, 1):
            for y in (height0, height1):
                xz = e[0]+n*(half_thick*sgn if offs is None else offs[(sgn+1)//2])
                corners.append((xz[0], y, xz[1]))
    c = np.array(corners)  # index = e*4 + s*2 + y
    faces = [(0, 1, 3, 2), (4, 6, 7, 5), (0, 4, 5, 1), (2, 3, 7, 6), (1, 5, 7, 3), (0, 2, 6, 4)]
    tris = []
    for f in faces:
        a, b, c2, d = [c[i] for i in f]
        nrm = np.cross(b-a, d-a); l = np.linalg.norm(nrm) or 1; nrm = nrm/l
        # plank-grain UVs: along the rail -> V across the long cream plank (u 0.05..0.27, v 0.05..0.95)
        quad_uv = {}
        for idx, p in zip(f, (a, b, c2, d)):
            along = idx // 4; up = (idx % 2)
            quad_uv[tuple(np.round(p, 3))] = (0.15+0.03*up, 0.48+0.06*along)   # small plain patch of the plank: no atlas detail smeared along the rail
        for tri in ((a, b, c2), (a, c2, d)):
            tris.append([(np.array(p), quad_uv[tuple(np.round(p, 3))], nrm, 0xffffffff) for p in tri])
    return tris

def build(season, size):
    segs = native_fence(season, size)
    tris = []
    for a, b in segs:
        p0 = np.array([a[0], a[1]], float); p1 = np.array([b[0], b[1]], float)
        L = np.linalg.norm(p1-p0); t = (p1-p0)/L; n = np.array([-t[1], t[0]])
        count = max(1, round(L/PITCH)); step = L/count
        for k in range(count+1):
            c = p0+t*step*k
            for tri in picket_tris:
                tt = []
                for (pos, uv, nrm, col) in tri:
                    u, v = pos[2], pos[0]
                    xz = c+t*u*S+n*v*S
                    nn = np.array([nrm[2]*t[0]+nrm[0]*n[0], nrm[1], nrm[2]*t[1]+nrm[0]*n[1]])
                    tt.append((np.array([xz[0], pos[1]*S, xz[1]]), uv, nn, col))
                tris.append(tt)
        # New Leaf rail: 6 tall, 1.9 deep, sitting against the inner face of the pickets
        inward = 1.0 if np.dot(CENTRE-(p0+p1)/2, n) > 0 else -1.0
        tris += box(p0, p1, t, 9*S, 15.03*S, 0, rail_uv, offs=sorted([inward*1.45*S, inward*3.3*S]))
    return tris

