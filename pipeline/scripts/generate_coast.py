"""Original New Leaf cliff/sand cells and native coastline coverage only."""
from pathlib import Path
import re
import numpy as np
from PIL import Image, ImageFilter

ROOT=Path(__file__).resolve().parent
SRC=ROOT/'terrain_source'
CODE=ROOT/'ACGC-PC-Port'
assets=(CODE/'pc/src/pc_assets.c').read_text()
rel=(ROOT/'foresta.rel').read_bytes()
def indices(name,w,h):
    m=re.search(r'\{"assets/'+name+r'\.bin",.*?, (0x[0-9A-F]+), (0x[0-9A-F]+),',assets)
    size,off=(int(v,16) for v in m.groups()); b=rel[off:off+size]
    a=np.zeros((h,w),np.uint8); n=0
    for ty in range(0,h,8):
        for tx in range(0,w,8):
            for y in range(8):
                for x in range(8):
                    a[ty+y,tx+x]=(b[n//2]>>(4 if n%2==0 else 0))&15; n+=1
    return a
def array(name,a):
    b=a.astype(np.uint8).tobytes()
    return 'static const unsigned char '+name+'[] = {\n'+''.join(','.join(map(str,b[i:i+32]))+',\n' for i in range(0,len(b),32))+'};\n'
out=['/* Generated by generate_coast.py. Donor RGB is ungraded. */\n']
# Cliff A is a fixed town geology choice, not the town's grass pattern or season.
for name,path in [('cliff','cliffA/tex_cliff01.png'),('cliff_normal','cliffA/tex_cliff01_n.png')]:
    a=np.array(Image.open(SRC/path).convert('RGBA'))
    if name=='cliff_normal':
        # TXOB format6 is HILO8/RG8. Ohana incorrectly exports it as LA8:
        # PNG RGB=raw byte0, alpha=raw byte1; hardware RG=(byte1,byte0).
        a=a[:,:,[3,0,1,2]].copy(); a[:,:,2]=0; a[:,:,3]=255
    out.append(array('pc_coast_'+name,a))
for season in range(10):
    beach=Image.open(SRC/f'grassA_season{season:02}/tex_beach.png').convert('RGBA').resize((128,128),Image.Resampling.BILINEAR)
    out.append(array(f'pc_coast_beach_{season}',np.asarray(beach)))
out.append('static const unsigned char* pc_coast_beach_seasons[10]={'+','.join(f'pc_coast_beach_{s}' for s in range(10))+'};\n')
for style in range(3):
    suffix='' if style==0 else '_'+str(style+1)
    for surface,h in [('cliff',64),('sand',32)]:
        idx=indices(f'mFM_grd_s_{surface}{suffix}_tex',64,h)
        # Keep the width of the original rim while removing its old star blades.
        coverage=np.minimum.accumulate((idx<4).mean(axis=1))
        if surface=='cliff':
            # Native upper shelf spans V=0..0.25; the wall starts at V=0.25.
            # Carry matching lawn across that shelf and feather into the wall.
            t=np.clip((np.arange(h)/(h-1)-0.18)/0.23,0,1)
            coverage=1-t*t*(3-2*t)
        mask=Image.fromarray(np.rint(np.broadcast_to(coverage[:,None],(h,64))*255).astype(np.uint8)).resize((128,128),Image.Resampling.BILINEAR)
        a=np.asarray(mask); assert np.array_equal(a[:,0],a[:,-1])
        out.append(array(f'pc_coast_{surface}_edge_{style}',a))
shore=indices('mFM_grd_beachA_tex',64,32)*17
# Its binary native contour depended on a separate old surf mesh. Give the
# continuous donor foam strip a smooth coverage field, repeating only across U.
padded=np.pad(np.pad(shore,((0,0),(8,8)),mode='wrap'),((8,8),(0,0)),mode='edge')
shore=Image.fromarray(padded).filter(ImageFilter.GaussianBlur(2)).crop((8,8,72,40))
out.append(array('pc_coast_shore_edge',np.asarray(shore.resize((128,128),Image.Resampling.BILINEAR))))
for surface in ['cliff','sand']:
    out.append('static const unsigned char* pc_coast_'+surface+'_edges[3]={'+','.join(f'pc_coast_{surface}_edge_{i}' for i in range(3))+'};\n')
(CODE/'pc/src/pc_coast_data.c_inc').write_text(''.join(out))
print('Generated original cliff/normal, ten seasonal beach cells and wrap-safe rim coverage.')
