"""New Leaf mailbox body for the native mailbox actor (flag joint and delivery animation stay native)."""
import json
from pathlib import Path
import numpy as np
from PIL import Image
import native_models as nm

ROOT = Path(__file__).resolve().parent
P = ROOT/'house_source/post/hobj_post_00'
SX, SY = 120.0, 91.0
m = json.loads(next((P/'hobj_post_00').glob('*.json')).read_text())['meshes'][0]
vs = m['vertices']
n = len(vs)//3; parent = list(range(n))
def find(x):
    while parent[x] != x: parent[x] = parent[parent[x]]; x = parent[x]
    return x
seen = {}
for i in range(n):
    for v in vs[3*i:3*i+3]:
        k = tuple(round(c, 2) for c in v['position'])
        if k in seen: parent[find(i)] = find(seen[k])
        else: seen[k] = i
comps = {}
for i in range(n): comps.setdefault(find(i), []).append(i)
keep = []; flag = []
for idx in comps.values():
    Pp = np.array([vs[3*i+j]['position'] for i in idx for j in range(3)])
    (flag if Pp[:, 0].max() < -10.3 else keep).extend(idx)
body = [v for i in sorted(keep) for v in vs[3*i:3*i+3]]
flagv = [v for i in sorted(flag) for v in vs[3*i:3*i+3]]
body_n = len(body); body = body+flagv      # box+post first, raised flag sign last
pts = np.array([v['position'] for v in body]); xc = (pts[:, 0].min()+pts[:, 0].max())/2; zc = (pts[:, 2].min()+pts[:, 2].max())/2
def tr(p): return ((p[2]-zc)*SX, (p[1]+1.7)*SY, -(p[0]-xc)*SX)

out = ['/* Generated by generate_mailbox.py from original hobj_post_00 (box and post only). */', 'int g_pc_mailbox = 0; /* GC mailbox kept (upscaled texture via texture pack) */']
def tex_array(name, path):
    im = Image.open(path).convert('RGBA'); w, h = im.size; data = bytearray()
    for ty in range(0, h, 4):
        for tx in range(0, w, 4):
            tile = [im.getpixel((tx+x, ty+y)) for y in range(4) for x in range(4)]
            data.extend(c for r, g, b, a in tile for c in (a, r)); data.extend(c for r, g, b, a in tile for c in (g, b))
    out.append(f'static u8 {name}[] ATTRIBUTE_ALIGN(32) = {{'); out.extend(','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32)); out.append('};')
    return w, h
w, h = tex_array('pc_mailbox_tex_s', P/'Textures/season00_raw.png'); tex_array('pc_mailbox_tex_w', P/'Textures/season09_raw.png')
out.append('static const PC_TreeSourceLight pc_mailbox_light[] = {')
for v in body:
    nn = v['normal']; l = sum(c*c for c in nn)**.5 or 1
    out.append('{{%s},{%s}},' % (','.join('%.6ff' % (c/l) for c in nn), ','.join(str((v['color'] >> b) & 255) for b in (16, 8, 0, 24))))
out.append('};'); out.append('static Vtx pc_mailbox_v[] ATTRIBUTE_ALIGN(32) = {')
for v in body:
    x, y, z = tr(v['position']); u, t = v['uv']
    out.append('{{{%d,%d,%d},1,{%d,%d},{%s}}},' % (round(x), round(y), round(z), max(-32768, min(32767, round(u*w*32))), max(-32768, min(32767, round((1-t)*h*32))),
               ','.join(str((v['color'] >> s) & 255) for s in (16, 8, 0, 24))))
out.append('};')
for season in 'swUV':
    up = season in 'UV'; tex = 's' if season in 'sU' else 'w'
    nverts = len(body) if up else body_n
    out += [f'static Gfx pc_mailbox_{season}_dl[] = {{', 'gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),', 'gsDPSetPrimColor(0,128,255,255,255,255),',
            'gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,0,0,0,COMBINED),', 'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_OPA_SURF2),',
            f'gsDPSetTextureImage_Dolphin(G_IM_FMT_RGBA,G_IM_SIZ_32b,{w},{h},pc_mailbox_tex_{tex}),',
            'gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE,0,0,GX_MIRROR,GX_MIRROR,0,0),',
            'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_CULL_BACK|G_FOG|G_SHADING_SMOOTH|G_DECAL_LEQUAL),']
    for base in range(0, nverts, 30):
        count = min(30, nverts-base)
        out.append(f'gsSPVertex(&pc_mailbox_v[{base}],{count},0),')
        idx = list(range(count)); out.append('gsSPNTrianglesInit_5b(%d,%s),' % (count//3, ','.join(map(str, (idx+[0]*9)[:9]))))
        for i in range(9, count, 12): out.append('gsSPNTriangles_5b(%s),' % ','.join(map(str, (idx[i:i+12]+[0]*12)[:12])))
    out += ['gsDPPipeSync(),', 'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_TEX_EDGE2),', 'gsDPSetTexEdgeAlpha(144),',
            'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_CULL_BACK|G_FOG|G_LIGHTING|G_SHADING_SMOOTH|G_DECAL_LEQUAL),', 'gsSPEndDisplayList(),', '};']
out += ['Gfx* pc_mailbox_body(int winter, int up) {', 'static unsigned generation;', 'if (!g_pc_mailbox) return NULL;',
        f'if (generation != pc_tree_light_generation) {{ pc_tree_light_vertices(pc_mailbox_v,pc_mailbox_light,{len(body)}); generation = pc_tree_light_generation; }}',
        'return up ? (winter ? pc_mailbox_V_dl : pc_mailbox_U_dl) : (winter ? pc_mailbox_w_dl : pc_mailbox_s_dl);', '}']
(ROOT/'ACGC-PC-Port/pc/src/pc_mailbox.c_inc').write_text('\n'.join(out)+'\n')
print('mailbox tris', len(body)//3)
