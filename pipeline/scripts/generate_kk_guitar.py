"""K.K. Slider's New Leaf guitar in place of the GameCube one.

The GC guitar is part of K.K.'s base display list (end_1 base_end_model: the triangles textured with the guitar
pieces of his body atlas, anime_4 + 0x080/0x140/0x180/0x400/0x440/0x480). generate_chr_smooth.py leaves those
triangles out and calls pc_kk_guitar_dl first in that list, so the guitar is drawn with the base joint's matrix.
The New Leaf guitar (the 'cloth' mesh of Npc/Special/Model/end) is fitted onto the GC guitar: the axis mapping and
scale that best match the GC guitar's bounding box and where its mass sits (the body end vs the neck), centred on it.

Output: pc/src/pc_kk_guitar.c_inc (included by pc_chr_smooth.c).
"""
import json, re, itertools
from pathlib import Path
import numpy as np
from PIL import Image
import native_models as nm
import generate_chr_smooth as g

ROOT = Path(__file__).resolve().parent
SRC = ROOT/'kk_source/Npc_Special_Model_end'
OUT = ROOT/'ACGC-PC-Port/pc/src/pc_kk_guitar.c_inc'
GUITAR_TEX = ('0x080', '0x140', '0x180', '0x400', '0x440', '0x480')

def gc_guitar_points():
    text = (ROOT/'ACGC-PC-Port/src/data/npc/model/mdl/end_1.c').read_text()
    va = {a: nm.vertices(a) for a in set(re.findall(r'gsSPVertex\(&?(\w+)', text)) if a in nm.sym}
    body = re.search(r'Gfx base_end_model\[\] = \{(.*?)\n\};', text, re.S).group(1)
    items, _ = g.parse_dl(re.sub(r'//[^\n]*', '', body), va)
    cur = ''; pts = []
    for k, v in items:
        if k == 'state' and 'LoadTextureBlock' in v: cur = v
        if k == 'tris' and any(f'anime_4_txt + {t}' in cur for t in GUITAR_TEX):
            pts += [x.p for t in v for x in t]
    return np.array(pts, float)

def main():
    G = gc_guitar_points()
    d = json.load(open(SRC/'end.json'))
    mesh = [m for m in d['meshes'] if m['texture'] == 'cloth'][0]
    vs = mesh['vertices']
    P = np.array([v['position'] for v in vs], float)
    gmin, gmax = G.min(0), G.max(0); gext = gmax-gmin; gc = (gmin+gmax)/2
    gmass = (G.mean(0)-gc)/np.maximum(gext/2, 1e-6)
    best = None
    for perm in itertools.permutations(range(3)):
        for signs in itertools.product((1, -1), repeat=3):
            M = np.zeros((3, 3))
            for i in range(3): M[i, perm[i]] = signs[i]           # GC axis i = sign * NL axis perm[i]
            Q = P @ M.T
            qmin, qmax = Q.min(0), Q.max(0); qext = qmax-qmin
            s = (gext.max())/(qext.max())
            shape = np.abs(qext*s-gext).sum()/gext.sum()
            qc = (qmin+qmax)/2
            mass = (Q.mean(0)-qc)/np.maximum(qext/2, 1e-6)
            score = shape+0.8*np.abs(mass-gmass).sum()
            if best is None or score < best[0]: best = (score, M, s, qc)
    _, M, s, qc = best
    def place(p): return ((np.array(p, float) @ M.T)-qc)*s+gc
    print('fit score', round(best[0], 3), 'scale', round(s, 1), 'GC guitar', gext.astype(int))
    im = Image.open(SRC/'cloth.png').convert('RGBA'); tw, th = im.size
    out = ['/* Generated by generate_kk_guitar.py: K.K. Slider\'s New Leaf guitar (base joint space). */']
    data = bytearray()
    for ty in range(0, th, 4):
        for tx in range(0, tw, 4):
            tile = [im.getpixel((tx+x, ty+y)) for y in range(4) for x in range(4)]
            data.extend(c for r, g_, b, a in tile for c in (a, r)); data.extend(c for r, g_, b, a in tile for c in (g_, b))
    out.append('static u8 pc_kk_guitar_tex[] ATTRIBUTE_ALIGN(32) = {')
    out += [','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32)]; out.append('};')
    out.append('static Vtx pc_kk_guitar_v[] ATTRIBUTE_ALIGN(32) = {')
    for i in range(0, len(vs), 3):
        tri = vs[i:i+3]
        su = 2*np.floor(min(v['uv'][0] for v in tri)/2); sv = 2*np.floor(min(v['uv'][1] for v in tri)/2)
        for v in tri:
            p = place(v['position']); n = np.array(v['normal'], float) @ M.T; n /= max(np.linalg.norm(n), 1e-9)
            out.append('{{{%d,%d,%d},0,{%d,%d},{%s,255}}},' % (round(p[0]), round(p[1]), round(p[2]),
                       round((v['uv'][0]-su)*tw*32), round((1-(v['uv'][1]-sv))*th*32),
                       ','.join(str(int(round(c*120)) & 255) for c in n)))
    out.append('};')
    dl = ['Gfx pc_kk_guitar_dl[] = {', 'gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),',
          'gsDPSetPrimColor(0,128,255,255,255,255),',
          'gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,0,0,0,COMBINED),',
          'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_TEX_EDGE2),',
          'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_CULL_BACK|G_FOG|G_LIGHTING|G_SHADING_SMOOTH),',
          f'gsDPSetTextureImage_Dolphin(G_IM_FMT_RGBA,G_IM_SIZ_32b,{tw},{th},pc_kk_guitar_tex),',
          'gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE,0,0,GX_MIRROR,GX_MIRROR,0,0),']
    for base in range(0, len(vs), 30):
        k = min(30, len(vs)-base); dl.append(f'gsSPVertex(&pc_kk_guitar_v[{base}],{k},0),')
        dl += [f'gsSP1Triangle({j},{j+1},{j+2},0),' for j in range(0, k, 3)]
    dl += ['gsDPPipeSync(),', 'gsSPEndDisplayList(),', '};']
    OUT.write_text('\n'.join(out+dl)+'\n')

if __name__ == '__main__':
    main()
