"""3D New Leaf fences for the GameCube villager houses, replacing their flat cut-out fences.

Each GC house's fence line (read off its fence quads) gets the closest-looking 3DS fence, one straight run of the
donor model repeated along every segment and scaled to the GC fence height. The donor texture is tinted to the
GC fence colour of each palette (a..e) and season, so every house variant keeps its own fence colour.
Output: Gfx pc_vf_{s|w}{house}_{a..e}[] in pc_villager_fences.c_inc, called from the smoothed house lists.
"""
import numpy as np
from pathlib import Path
from PIL import Image, ImageDraw
import native_models as nm
import fence_runs

ROOT = Path(__file__).resolve().parent
# house -> (donor fence, fence height, fence polylines (x, z) in house model space)
HOUSES = {
    1: ('hobj_fence_01', 2600, [[(4500, 4000), (4500, 7250), (-5250, 7250), (-5250, 5333)],      # lower, and behind the name sign
                                [(4500, 0), (4500, -3250), (-5250, -3250), (-5250, -1333)]]),
    2: ('hobj_fence_02', 2250, [[(4500, 5000), (4500, 7000), (-5000, 7000)], [(4500, -1000), (4500, -3000), (-5000, -3000)]]),
    3: ('int_fence_10', 2250, [[(-5000, -5000), (-5000, 4250), (-3000, 4250)], [(5000, -5000), (5000, 4250), (3000, 4250)]]),
    4: ('int_fence_10', 2250, [[(5125, 5000), (5125, 7125), (-5000, 7125), (-5000, -3125), (5125, -3125), (5125, -1000)]]),
    5: ('int_fence_10', 2250, [[(5125, 5000), (5125, 7000), (-5000, 7000), (-5000, -3000), (5125, -3000), (5125, -1000)]]),
}
from generate_villager_fences_defs import FENCE_PART, is_fence_tri

SINK = 200.0
PACK = {2: 0.7}            # house 2: log posts closer than the donor's
def gc_fence_colour(season, n, letter):
    d = nm.parse_model_file(ROOT/'ACGC-PC-Port/src/data/model/obj_s_house1.c')
    cols = []
    for t in d.get(f'obj_{season}_house{n}_{FENCE_PART[n]}_model', []):
        if not is_fence_tri([v[:3] for v in t[5]]): continue
        w, h = t[3], t[4]
        a = np.asarray(nm.decode_ci(nm.blob(t[0]), w, h, nm.palette(f'obj_{season}_house{n}_{letter}_pal'), 4).convert('RGBA')).astype(float)
        m = Image.new('L', (w, h), 0)
        ImageDraw.Draw(m).polygon([(float(v[3]) % w, float(v[4]) % h) for v in t[5]], fill=255)
        sel = (np.asarray(m) > 0) & (a[..., 3] > 128)
        if sel.any(): cols.append(a[sel][:, :3])
    c = np.concatenate(cols) if cols else np.array([[140.0, 90, 50]])
    lum = c @ [0.3, 0.59, 0.11]
    return c[(lum > np.percentile(lum, 50)) & (lum < np.percentile(lum, 97))].mean(0)

def tinted(tex_path, target):
    """recolour the donor fence to the GC fence colour, keeping its own light/dark detail; snow stays white"""
    a = np.asarray(Image.open(tex_path).convert('RGBA')).astype(float).copy()
    rgb = a[..., :3]; lum = rgb @ np.array([0.3, 0.59, 0.11])
    snow = (rgb[..., 2] > 200) & (rgb.min(-1) > 185) & (rgb[..., 2] >= rgb[..., 0])
    body = ~snow
    if '09' in str(tex_path): pass
    ref = np.median(lum[body]) if body.any() else 128.0
    new = target[None, None, :]*(0.6+0.4*np.clip(lum/max(ref, 1), 0, 2.0))[..., None]
    a[..., :3] = np.where(body[..., None], np.clip(new, 0, 255), rgb)
    a[..., 3] = 255          # donor alpha is a gloss mask (alpha test off on 3DS), not transparency
    return Image.fromarray(a.astype(np.uint8), 'RGBA')

def gx_rgba8(im):
    w, h = im.size; data = bytearray()
    for ty in range(0, h, 4):
        for tx in range(0, w, 4):
            tile = [im.getpixel((tx+x, ty+y)) for y in range(4) for x in range(4)]
            data.extend(c for r, g, b, a in tile for c in (a, r)); data.extend(c for r, g, b, a in tile for c in (g, b))
    return data

out = ['/* Generated by generate_villager_fences.py: 3DS 3D fences for the GC villager houses. */']
for n, (donor, H, paths) in HOUSES.items():
    post, rails, spacing, (L, RH, RW), tex, out_sign = fence_runs.parts(donor)
    # only whole posts: the donor run also holds off-cuts (half logs, open-topped stubs, slivers) that read as holes
    best = max(len(p_) for p_ in post)
    post = [p_ for p_ in post if len(p_) == best][:1]
    gcv = np.array([v[:3] for p_ in ('t1', 't2') for t_ in nm.parse_model_file(ROOT/'ACGC-PC-Port/src/data/model/obj_s_house1.c').get(f'obj_s_house{n}_{p_}_model', []) for v in t_[5]], float)
    centre = np.array([gcv[:, 0].mean(), gcv[:, 2].mean()])
    S = H/RH
    verts = []
    for path in paths:
        for (x0, z0), (x1, z1) in zip(path, path[1:]):
            p0 = np.array([x0, z0], float); p1 = np.array([x1, z1], float); seg = np.linalg.norm(p1-p0)
            t = (p1-p0)/seg; nrm = np.array([-t[1], t[0]])
            if np.dot(nrm, (p0+p1)/2-centre) < 0: nrm = -nrm      # point away from the house...
            nrm = nrm*out_sign                                   # ...so the fence's outside faces out (and the camera)
            # clean cut: posts evenly spaced from end to end (one exactly at each end), rails stretched between
            # the first and last post; spacing is the donor's own (times PACK)
            gap = spacing*S*PACK.get(n, 1.0); m = max(1, int(round(seg/gap)))
            pieces = [(p0+t*(seg*j/m), post[j % len(post)], 1.0) for j in range(m+1)]
            if rails:
                ru = np.array([v[0][0] for g_ in rails for tri in g_ for v in tri]); r0, r1 = ru.min(), ru.max()
                rs = seg/max((r1-r0)*S, 1e-6)
                pieces += [(p0-t*(r0*S*rs), [tri for g_ in rails for tri in g_], rs)]
            for base, use, su_ in pieces:
                su = S*su_
                for tri in use:
                    for p, uv, nn in tri:
                        xz = base+t*(p[0]*su)+nrm*(p[2]*S)
                        nw = np.array([nn[0]*t[0]+nn[2]*nrm[0], nn[1], nn[0]*t[1]+nn[2]*nrm[1]])
                        nw /= max(np.linalg.norm(nw), 1e-9)
                        nw = nw*0.45+np.array([0, 0.85, 0]); nw /= np.linalg.norm(nw)   # bias up: lit like the house, never black from behind
                        verts.append(((xz[0], p[1]*S-SINK, xz[1]), uv, nw))   # sunk into the ground
    tw, th = Image.open(tex[0]).size
    out.append(f'static Vtx pc_vf{n}_v[] ATTRIBUTE_ALIGN(32) = {{')
    for i in range(0, len(verts), 3):
        tri = verts[i:i+3]
        su_ = 2*np.floor(min(v[1][0] for v in tri)/2); sv_ = 2*np.floor(min(v[1][1] for v in tri)/2)
        for pos, uv, nw in tri:
            nb = ','.join(str(int(round(c*126)) & 255) for c in nw)
            out.append('{{{%d,%d,%d},0,{%d,%d},{%s,255}}},' % (round(pos[0]), round(pos[1]), round(pos[2]),
                       round((uv[0]-su_)*tw*32), round((1-(uv[1]-sv_))*th*32), nb))
    out.append('};')
    geo = [f'static Gfx pc_vf{n}_geo[] = {{']
    for base in range(0, len(verts), 30):
        c = min(30, len(verts)-base)
        geo.append(f'gsSPVertex(&pc_vf{n}_v[{base}],{c},0),')
        for k_ in range(0, c, 3): geo.append(f'gsSP1Triangle({k_},{k_+1},{k_+2},0),')
    out += geo+['gsSPEndDisplayList(),', '};']
    for season in 'sw':
        for letter in 'abcde':
            name = f'pc_vf_{season}{n}_{letter}'
            im = tinted(tex[1 if season == 'w' else 0], gc_fence_colour('s', n, letter)).convert('RGBA')   # winter: same wood, donor's own snow
            if im.size != (tw, th): im = im.resize((tw, th))
            data = gx_rgba8(im)
            out.append(f'static u8 {name}_tex[] ATTRIBUTE_ALIGN(32) = {{'); out.extend(','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32)); out.append('};')
            out += [f'Gfx {name}[] = {{', 'gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),', 'gsDPSetPrimColor(0,128,255,255,255,255),',
                    'gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,0,0,0,COMBINED),',
                    'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_OPA_SURF2),',
                    f'gsDPSetTextureImage_Dolphin(G_IM_FMT_RGBA,G_IM_SIZ_32b,{tw},{th},{name}_tex),',
                    'gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE,0,0,GX_MIRROR,GX_MIRROR,0,0),',
                    'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_FOG|G_LIGHTING|G_SHADING_SMOOTH),',
                    f'gsSPDisplayList(pc_vf{n}_geo),', 'gsDPPipeSync(),', 'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_TEX_EDGE2),', 'gsSPEndDisplayList(),', '};']
    print('house', n, donor, 'tris', len(verts)//3, 'scale', round(S, 1))
(ROOT/'ACGC-PC-Port/pc/src/pc_villager_fences.c_inc').write_text('\n'.join(out)+'\n')
