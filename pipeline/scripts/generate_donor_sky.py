"""Generate donor sky mask and rasterized cloud density/coverage, no palette."""
from pathlib import Path
from PIL import Image
import json
import math
import numpy as np

root = Path(__file__).resolve().parent
mask = Image.open(root / 'terrain_source/Sky/tex_sky.png').convert('RGBA')
# Sky.bcres UVs run U vertically and V horizontally. Retain the actual mask;
# the screen-space backdrop is an approximation of the donor camera mapping.
out = Image.new('RGBA', (256, 128))
for y in range(128):
    for x in range(256):
        r, _, _, a = mask.getpixel((127-y, x))
        out.putpixel((x,y), (r,r,r,a))
# The source mask uses alternating one-texel luminance stipple. Its intended
# small-screen footprint averages those texels; magnifying them on PC exposes
# a checkerboard. Area-filter pairs before reconstruction, preserving the
# source average rather than changing either endpoint of the runtime palette.
out = out.resize((128,64), Image.Resampling.BOX).resize((256,128), Image.Resampling.BILINEAR)
out.save(root / 'terrain_source/Sky/donor-sky-mask.png')
data = bytearray()
for ty in range(0,128,4):
    for tx in range(0,256,4):
        tile = [out.getpixel((tx+x,ty+y)) for y in range(4) for x in range(4)]
        data.extend(c for r,g,b,a in tile for c in (a,r))
        data.extend(c for r,g,b,a in tile for c in (g,b))
lines = ['/* Generated by generate_donor_sky.py from /VrBox/Sky.bcres.',
         ' * Grayscale mask; runtime Sky_m: C1*(1-texture.r) + C0*texture.r. */',
         'static u8 pc_donor_sky_tex[] ATTRIBUTE_ALIGN(32) = {']
lines += [','.join(map(str,data[i:i+32]))+',' for i in range(0,len(data),32)]
lines += ['};']

# Rasterize the donor's actual triangulated cloud sheet, rather than replace
# it with a flat tiled pattern. Alpha at its irregular edge comes from mesh
# vertices. UV0 feeds both repeat samplers; sampler1 rotates by one degree.
mesh = json.loads((root/'terrain_source/bg_cloud/bg_cloud.json').read_text())['meshes'][0]
verts = mesh['vertices']
positions = np.array([v['position'][:2] for v in verts])
lo, hi = positions.min(axis=0), positions.max(axis=0)
cw,ch = 256,128
pos = (positions-lo)/(hi-lo)*np.array([cw,ch])
pos[:,1] = ch-pos[:,1]
tex = np.array(Image.open(root/'terrain_source/bg_cloud/tex_cloud.png').convert('RGBA'), dtype=float)[:,:,0]/255.
density = np.zeros((ch,cw),dtype=float)
coverage = np.zeros((ch,cw),dtype=float)
uv_field = np.zeros((ch,cw,2),dtype=float)

def sample(uv):
    # CGFX UV origin is at the bottom; PNG origin is at the top.
    x = uv[...,0]*128-.5
    y = (1-uv[...,1])*128-.5
    ix,iy = np.floor(x).astype(int),np.floor(y).astype(int)
    fx,fy = x-ix,y-iy
    return (tex[iy%128,ix%128]*(1-fx)*(1-fy)+tex[iy%128,(ix+1)%128]*fx*(1-fy)+
            tex[(iy+1)%128,ix%128]*(1-fx)*fy+tex[(iy+1)%128,(ix+1)%128]*fx*fy)

# Cached sampler1 matrix from bg_cloud.bcres MTOB coordinator1. Preserve its
# rotation-center compensation, rather than reconstruct rotation at origin.
rot = np.array([[.9998477101325989,-.017452405765652657],
                [.017452405765652657,.9998477101325989]])
offset = np.array([-.9911976456642151,-1.0086500644683838])
for i in range(0,len(verts),3):
    p = pos[i:i+3]
    x0,y0 = np.maximum(np.floor(p.min(axis=0)).astype(int),[0,0])
    x1,y1 = np.minimum(np.ceil(p.max(axis=0)).astype(int),[cw,ch])
    if x1<=x0 or y1<=y0: continue
    yy,xx = np.mgrid[y0:y1,x0:x1]+.5
    det = (p[1,1]-p[2,1])*(p[0,0]-p[2,0])+(p[2,0]-p[1,0])*(p[0,1]-p[2,1])
    if abs(det)<1e-8: continue
    a=((p[1,1]-p[2,1])*(xx-p[2,0])+(p[2,0]-p[1,0])*(yy-p[2,1]))/det
    b=((p[2,1]-p[0,1])*(xx-p[2,0])+(p[0,0]-p[2,0])*(yy-p[2,1]))/det
    c=1-a-b
    inside=(a>=-1e-6)&(b>=-1e-6)&(c>=-1e-6)
    weights=np.stack([a,b,c],axis=-1)
    uv=weights@np.array([v['uv'] for v in verts[i:i+3]])
    cov=weights@np.array([(v['color']>>24)/255 for v in verts[i:i+3]])
    den=.5*(sample(uv)+sample(uv@rot.T+offset))
    density[y0:y1,x0:x1][inside]=den[inside]
    coverage[y0:y1,x0:x1][inside]=cov[inside]
    uv_field[y0:y1,x0:x1][inside]=uv[inside]

# Keep the original fan's nonuniform UV projection instead of repeating a
# flat tile. Its center is the visible window; outer polygon boundaries are
# deliberately offscreen, as required by the source sheet's opaque edges.
# Window placement is reference-calibrated, not a decoded donor camera.
crop=(((-280-lo[0])/(hi[0]-lo[0]))*cw,
      ((hi[1]-620)/(hi[1]-lo[1]))*ch,
      (((280-lo[0])/(hi[0]-lo[0]))*cw),
      ((hi[1]-120)/(hi[1]-lo[1]))*ch)
def crop_sheet(arr):
    im=Image.fromarray(arr.astype(np.float32),mode='F')
    return np.asarray(im.transform((cw,ch),Image.Transform.EXTENT,crop,Image.Resampling.BILINEAR))
density=crop_sheet(density)
coverage=crop_sheet(coverage)
uv_field=np.stack([crop_sheet(uv_field[:,:,axis]) for axis in range(2)],axis=-1)

for name,arr in [('density',density),('coverage',coverage)]:
    values=np.rint(np.clip(arr,0,1)*255).astype(np.uint8)
    Image.fromarray(values).save(root/f'terrain_source/bg_cloud/cloud-{name}.png')
    lines += [f'/* Row-major {cw}x{ch} donor cloud {name}; not GX tiled. */',
              f'static const u8 pc_donor_cloud_{name}[{cw*ch}] = {{']
    flat=values.ravel().tolist()
    lines += [','.join(map(str,flat[j:j+32]))+',' for j in range(0,len(flat),32)]
    lines += ['};']
lines += [f'#define PC_DONOR_CLOUD_WIDTH {cw}',f'#define PC_DONOR_CLOUD_HEIGHT {ch}']
lines += ['/* Source fan UV0, signed fixed point with 12 fractional bits. */',
          f'static const s16 pc_donor_cloud_uv[{cw*ch*2}] = {{']
flat=np.rint(uv_field*4096).astype(np.int16).ravel().tolist()
lines += [','.join(map(str,flat[i:i+24]))+',' for i in range(0,len(flat),24)]
lines += ['};','/* Original tex_cloud red channel; PNG row origin is top. */',
          'static const u8 pc_donor_cloud_mask[128*128] = {']
flat=np.rint(tex*255).astype(np.uint8).ravel().tolist()
lines += [','.join(map(str,flat[i:i+32]))+',' for i in range(0,len(flat),32)]
lines += ['};']

def emit_rgba(name,im):
    data=bytearray()
    w,h=im.size
    for ty in range(0,h,4):
        for tx in range(0,w,4):
            tile=[im.getpixel((tx+x,ty+y))for y in range(4)for x in range(4)]
            data.extend(c for r,g,b,a in tile for c in (a,r))
            data.extend(c for r,g,b,a in tile for c in (g,b))
    lines.append(f'static u8 {name}[] ATTRIBUTE_ALIGN(32) = {{')
    lines.extend(','.join(map(str,data[i:i+32]))+',' for i in range(0,len(data),32))
    lines.append('};')

# Donor star material: alpha=clamp(2*(stars.r-cutoff)), RGB=clamp(2*noise.rgb).
# Runtime threshold is not decoded. A half-range cutoff matches the supplied
# clear-night reference's sparse points instead of the default dense field.
stars=Image.open(root/'terrain_source/bg_stars/stars.png').convert('RGBA')
noise=Image.open(root/'terrain_source/bg_stars/stars_noise.png').convert('RGBA')
stars_out=Image.new('RGBA',stars.size)
for y in range(256):
    for x in range(256):
        rgb=noise.getpixel((x%64,y%64))[:3]
        stars_out.putpixel((x,y),tuple(min(255,c*2) for c in rgb)+(max(0,min(255,(stars.getpixel((x,y))[0]-128)*2)),))
emit_rgba('pc_donor_stars_tex',stars_out)
# Moon crater colors use the actual front material's C0/C1 constants.
moon=Image.open(root/'terrain_source/bg_moon_nml/tex_moon.png').convert('RGBA')
moon_out=Image.new('RGBA',moon.size)
for y in range(32):
    for x in range(32):
        r,g,b,a=moon.getpixel((x,y)); t=r/255.
        moon_out.putpixel((x,y),(round(255*t+207*(1-t)),round(255*t+222*(1-t)),189,a))
emit_rgba('pc_donor_moon_tex',moon_out)

# Rasterize the actual moonlight mesh and mirrored 16x16 donor glow texture.
# Its original material is additive (src alpha, one), not ordinary opacity.
light_mesh=json.loads((root/'terrain_source/bg_moon_nml/bg_moon_nml.json').read_text())['meshes'][2]
lv=light_mesh['vertices']; lp=np.array([v['position'][:2] for v in lv])
lpos=lp/132*64+32; lpos[:,1]=64-lpos[:,1]
glow=np.asarray(Image.open(root/'terrain_source/bg_moon_nml/moon_light.png').convert('RGBA'))[:,:,0]/255.
halo=np.zeros((64,64),dtype=float)
for i in range(0,len(lv),3):
    p=lpos[i:i+3]; x0,y0=np.maximum(np.floor(p.min(axis=0)).astype(int),[0,0]);x1,y1=np.minimum(np.ceil(p.max(axis=0)).astype(int),[64,64])
    if x1<=x0 or y1<=y0:continue
    yy,xx=np.mgrid[y0:y1,x0:x1]+.5
    det=(p[1,1]-p[2,1])*(p[0,0]-p[2,0])+(p[2,0]-p[1,0])*(p[0,1]-p[2,1])
    if abs(det)<1e-8:continue
    a=((p[1,1]-p[2,1])*(xx-p[2,0])+(p[2,0]-p[1,0])*(yy-p[2,1]))/det
    b=((p[2,1]-p[0,1])*(xx-p[2,0])+(p[0,0]-p[2,0])*(yy-p[2,1]))/det;c=1-a-b
    inside=(a>=0)&(b>=0)&(c>=0)
    uv=np.stack([a,b,c],axis=-1)@np.array([v['uv']for v in lv[i:i+3]])
    uv=1-np.abs(np.mod(uv,2)-1)
    u=np.clip(uv[...,0]*15,0,15);v=np.clip((1-uv[...,1])*15,0,15)
    ix=np.floor(u).astype(int);iy=np.floor(v).astype(int);fx=u-ix;fy=v-iy
    den=glow[iy,ix]*(1-fx)*(1-fy)+glow[iy,np.minimum(ix+1,15)]*fx*(1-fy)+glow[np.minimum(iy+1,15),ix]*(1-fx)*fy+glow[np.minimum(iy+1,15),np.minimum(ix+1,15)]*fx*fy
    halo[y0:y1,x0:x1][inside]=den[inside]
halo_out=Image.new('RGBA',(64,64))
for y in range(64):
    for x in range(64):
        t=float(halo[y,x]);halo_out.putpixel((x,y),(round(255*t),round(255*t),round(189*t),255 if t>0 else 0))
emit_rgba('pc_donor_moon_halo_tex',halo_out)
halo_out.save(root/'terrain_source/bg_moon_nml/donor-moon-halo.png')
(root / 'ACGC-PC-Port/src/game/pc_donor_sky.c_inc').write_text('\n'.join(lines)+'\n')
