"""Original pine/palm shadow masks and canopy-fitted shadows for every tree stage.

Masks: /Shadow/sdw_fg_treeB and sdw_fg_treeC store one quadrant (center at the
bottom-left texel), reconstructed exactly like the existing sdw_fg_treeA mask.
Fit: each native young/mature shadow quad is scaled to its imported donor
canopy footprint at the shared importer scale, keeping the native sunlight
shear (same method as generate_tree_shadow_fit.py for the mature hardwood).
"""
import json, re, struct
from pathlib import Path
from PIL import Image, ImageOps
from generate_young_plants import split_standing, SCALE

R = Path(__file__).resolve().parent; O = R/'shadow_source'
def array(name, data):
    return 'static const unsigned char '+name+'[] = {\n'+'\n'.join(','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32))+'\n};\n'
out = '/* Generated by generate_plant_shadows.py: full 64x64 donor pine/palm masks. */\n'
for letter, name in (('B', 'pc_donor_cedar_shadow'), ('C', 'pc_donor_palm_shadow')):
    q = Image.open(O/f'sdw_fg_tree{letter}/sdw_fg_tree{letter}.png').convert('RGB').getchannel('R')
    for y in range(32):
        for x in (30, 31): q.putpixel((x, y), round(q.getpixel((x, y))*(31-x)/2))
    full = Image.new('L', (64, 64))
    full.paste(ImageOps.mirror(q), (0, 0)); full.paste(q, (32, 0))
    full.paste(ImageOps.flip(ImageOps.mirror(q)), (0, 32)); full.paste(ImageOps.flip(q), (32, 32))
    full.save(O/f'tree{letter}-full-mask.png')
    out += array(name, [c for v in full.getdata() for c in [v]*4])
(R/'ACGC-PC-Port/pc/src/pc_plant_shadow_data.c_inc').write_text(out)

rel = (R/'foresta.rel').read_bytes(); DATA = 0x2dd340
sym = {}
for line in open(R/'ACGC-PC-Port/config/GAFE01_00/foresta/symbols.txt'):
    m = re.match(r'(\w+) = \.data:0x([0-9A-F]+); // type:object size:0x([0-9A-F]+)', line)
    if m: sym[m[1]] = int(m[2], 16)
def mesh(name):
    return json.loads((R/'tree_source/season08_normals'/(name+'.json')).read_text())['meshes'][0]['vertices']
rows = []; audit = {}
# Native shadow list -> donor model whose canopy casts it.
for native, donor in (('tree3', 'fg_treeA_2'), ('tree4', 'fg_treeA_3'), ('tree5', 'fg_treeA_4'),
                      ('cedar3', 'fg_treeB_2'), ('cedar4', 'fg_treeB_3'), ('cedar5', 'fg_treeB_4'),
                      ('palm3', 'fg_treeC_2'), ('palm4', 'fg_treeC_3'), ('palm5', 'fg_treeC_4')):
    vs = mesh(donor)
    leaf = vs[79*3:] if donor == 'fg_treeA_4' else split_standing(vs)[0]  # mature: accepted partition
    src = [max(v['position'][a] for v in leaf)-min(v['position'][a] for v in leaf) for a in (0, 2)]
    quad = [struct.unpack_from('>hhh', rel, DATA+sym[f'obj_{native}_shadow_v']+i*16) for i in range(4)]
    nat = [max(v[a] for v in quad)-min(v[a] for v in quad) for a in (0, 2)]
    width, depth = [src[i]*SCALE/nat[i] for i in range(2)]
    center = (min(v['position'][2] for v in leaf)+max(v['position'][2] for v in leaf))*SCALE*.5
    rows.append((native, width, depth, center))
    audit[native] = {'donor': donor, 'canopy_xz_world': [x*SCALE*.01 for x in src], 'native_quad_xz': nat,
                     'width': width, 'depth': depth, 'center_z': center}
h = ['/* Generated by generate_plant_shadows.py: donor canopy / native quad ratios. */',
     '#ifndef PC_PLANT_SHADOW_FIT_H', '#define PC_PLANT_SHADOW_FIT_H']
h += [f'extern Gfx obj_{n}_shadowT_gfx_model[];' for n, *_ in rows]
h += ['static int pc_plant_shadow_fit(const Gfx* dl, float* width, float* depth, float* center_z) {',
      '    static const struct { const Gfx* dl; float width, depth, center_z; } fits[] = {']
h += ['        {obj_%s_shadowT_gfx_model,%.9ff,%.9ff,%.9ff},' % r for r in rows]
h += ['    };', '    unsigned i;', '    for(i=0;i<sizeof(fits)/sizeof(fits[0]);++i) if(fits[i].dl==dl) {',
      '        *width=fits[i].width; *depth=fits[i].depth; *center_z=fits[i].center_z; return 1;', '    }',
      '    return 0;', '}', '#endif']
(R/'ACGC-PC-Port/pc/include/pc_plant_shadow_fit.h').write_text('\n'.join(h)+'\n')
(O/'plant_shadow_fit.json').write_text(json.dumps(audit, indent=1))
for r in rows: print('%-7s width %.3f depth %.3f center %.0f' % r)
