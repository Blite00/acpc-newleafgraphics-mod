"""Rolling snowballs / snowmen: the New Leaf snowball (/Other/snowball.bcres, smooth 540-vertex sphere, 64x64 snow
texture) in place of the GC act_darumaA/B balls. Writes ACGC-PC-Port/src/actor/pc_nl_snowball.c_inc:
  pc_nl_snowball[]  body / rolling ball (act_darumaB)
  pc_nl_snowhead[]  ball + New Leaf snowman face A (coal eyes, carrot, coal mouth) for the head (act_darumaA)
ac_snowman.c / ac_psnowman.c draw these and collapse the GC vertices; PC_NL_SNOW=0 shows the GC balls."""
import json
from pathlib import Path
import numpy as np
from PIL import Image, ImageFilter
ROOT = Path(__file__).resolve().parent
D = ROOT/'furn_work/nl_ftr/snowball'
R_GC = 1040.0   # act_darumaA/B ball radius (verts span +-1024..1050)
FACE = 'snowball_faceA'
_a = np.radians(18.0)   # keeps the NL mouth under the GC carrot nose
FACE_TILT = np.array([[1, 0, 0], [0, np.cos(_a), np.sin(_a)], [0, -np.sin(_a), np.cos(_a)]])
ball = json.load(open(D/'snowball.json'))['meshes'][0]
P = np.array([v['position'] for v in ball['vertices']], float); c = (P.max(0)+P.min(0))/2
k = R_GC/np.linalg.norm(P-c, axis=1).max()
out = ['/* Generated by gen_snowball.py: New Leaf snowball (scale %.1f) */' % k]
def tex(name, im):
    w, h = im.size; data = bytearray()
    for ty in range(0, h, 4):
        for tx in range(0, w, 4):
            t = [im.getpixel((tx+x, ty+y)) for y in range(4) for x in range(4)]
            data.extend(cc for r, g, b, a in t for cc in (a, r)); data.extend(cc for r, g, b, a in t for cc in (g, b))
    out.append(f'static u8 {name}[] ATTRIBUTE_ALIGN(32) = {{'); out.extend(','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32)); out.append('};')
def verts(name, vs, w, h, sphere):
    out.append(f'static Vtx {name}[] ATTRIBUTE_ALIGN(32) = {{')
    for v in vs:
        q = np.array(v['position'], float)-c
        if not sphere: q = FACE_TILT@q   # the GC head is drawn tipped forward: raise the face to sit where the GC one does
        p = q*k
        n = q/np.linalg.norm(q) if sphere else FACE_TILT@np.array([0, 0, 1.0])   # face decals lie on the front of the ball
        nb = ','.join(str(int(round(x*126)) & 255) for x in n)
        out.append('{{{%d,%d,%d},0,{%d,%d},{%s,255}}},' % (round(p[0]), round(p[1]), round(p[2]), round(v['uv'][0]*w*32), round((1-v['uv'][1])*h*32), nb))
    out.append('};')
WRAP = {2: 'GX_REPEAT', 3: 'GX_MIRROR'}
def draw(vname, n, tname, w, h, cut, wu=2, wv=2):
    g = ['gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_TEX_EDGE2),' if cut else 'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_OPA_SURF2),',
         f'gsDPSetTextureImage_Dolphin(G_IM_FMT_RGBA,G_IM_SIZ_32b,{w},{h},{tname}),',
         f'gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE,0,0,{WRAP.get(wu, "GX_CLAMP")},{WRAP.get(wv, "GX_CLAMP")},0,0),']
    for b in range(0, n, 30):
        kk = min(30, n-b); g.append(f'gsSPVertex(&{vname}[{b}],{kk},0),'); g += [f'gsSP1Triangle({j},{j+1},{j+2},0),' for j in range(0, kk-2, 3)]
    return g
HEAD = ['gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),', 'gsDPSetPrimColor(0,128,255,255,255,255),',
        'gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,0,0,0,COMBINED),',
        'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_CULL_BACK|G_FOG|G_LIGHTING|G_SHADING_SMOOTH|G_DECAL_LEQUAL),']
# snow: NL lights it brightly and keeps a sparkle mask in alpha; GC lighting leaves it grey and speckled,
# so lift it toward white and keep a quarter of the grain
im = Image.open(D/'snowball_base.png').convert('RGBA'); px = np.array(im, float)
px[..., :3] = 255-(255-px[..., :3])*0.25; px[..., 3] = 255
im = Image.fromarray(px.astype(np.uint8), 'RGBA').filter(ImageFilter.GaussianBlur(0.8)); bw, bh = im.size
tex('pc_nl_snowball_tex', im); verts('pc_nl_snowball_v', ball['vertices'], bw, bh, True)
ball_draw = draw('pc_nl_snowball_v', len(ball['vertices']), 'pc_nl_snowball_tex', bw, bh, False)
# face decals (alpha-tested)
fm = json.load(open(D/f'{FACE}.json'))['meshes']
face_draw = []
for i, m in enumerate(fm):
    # bleed colour into the clear texels and cut at half alpha: the soft edges were filtering in dark/teal fringes
    import gen_furn
    fi = Image.open(D/f"{m['texture']}.png").convert('RGBA')
    px = np.array(fi, float); r, g, b = px[..., 0], px[..., 1], px[..., 2]
    nose = (r > 150) & (g > 60) & (b < 140) & (r > b+60)       # the NL carrot (the GC one is kept, ac_snowman.c) ...
    for _ in range(3):                                         # ... plus its outline
        nose = nose | np.roll(nose, 1, 0) | np.roll(nose, -1, 0) | np.roll(nose, 1, 1) | np.roll(nose, -1, 1)
    px[nose, 3] = 0
    px[px[..., 3] > 0, :3] = (22, 24, 28)                      # coal pieces flat black (no light-blue rim)
    fi = gen_furn.bleed(Image.fromarray(px.astype(np.uint8), 'RGBA'))
    # 4x smooth upscale before the cut so the coal pieces come out round instead of stair-stepped
    fi = fi.resize((fi.width*4, fi.height*4), Image.BICUBIC)
    fi.putalpha(fi.getchannel('A').point(lambda a: 255 if a > 128 else 0))
    w, h = fi.size; tex(f'pc_nl_snowface_tex{i}', fi); verts(f'pc_nl_snowface_v{i}', m['vertices'], w, h, False)
    face_draw += draw(f'pc_nl_snowface_v{i}', len(m['vertices']), f'pc_nl_snowface_tex{i}', w, h, True, m['mapper']['wrapU'], m['mapper']['wrapV'])
out += ['Gfx pc_nl_snowball[] = {'] + HEAD + ball_draw + ['gsDPPipeSync(),', 'gsSPEndDisplayList(),', '};']
out += ['Gfx pc_nl_snowhead[] = {'] + HEAD + ball_draw + face_draw + ['gsDPPipeSync(),', 'gsSPEndDisplayList(),', '};']
(ROOT/'ACGC-PC-Port/src/actor/pc_nl_snowball.c_inc').write_text('\n'.join(out)+'\n')
print('ok scale', round(k, 1), len(ball['vertices']), 'ball verts', sum(len(m['vertices']) for m in fm), 'face verts')
