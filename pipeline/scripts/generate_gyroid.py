"""New Leaf gyroid (int_hnw_ugaiM: peach clay, hat, round face) for the player-house save gyroid.

The model rides the native body joint of the GC gyroid skeleton, so its sway/talk animation is kept; the GC
head and hand joints are hidden. Scaled uniformly to the GC gyroid's height. Its 64x64 texture is upscaled
4x with Real-ESRGAN (mirror-padded like its wrap mode). Lit on the CPU with the same light as the trees.
"""
import json, shutil, subprocess
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent
NAME = 'int_hnw_ugaiM'
SRC = ROOT/'gyroid_source'/NAME
ESR = ROOT/'toolchain/realesrgan/realesrgan-ncnn-vulkan.exe'
W = ROOT/'gyroid_up'
GC_HEIGHT = 4000.0      # GC gyroid: ground (-419 in body-joint space) to hat top (head 2951 + 629)
FRONT = 1.0             # NL +z (face) -> body joint +Z

m = json.loads((SRC/f'{NAME}.json').read_text())['meshes'][0]
vs = m['vertices']
P = np.array([v['position'] for v in vs]); S = GC_HEIGHT/(P[:, 1].max()-P[:, 1].min())

# texture: mirror-pad, 4x Real-ESRGAN, crop
for d in ('in', 'out'):
    shutil.rmtree(W/d, ignore_errors=True); (W/d).mkdir(parents=True)
src = Image.open(SRC/f'{NAME}.png').convert('RGBA'); w, h = src.size; PAD = 8
Image.fromarray(np.pad(np.asarray(src.convert('RGB')), ((PAD, PAD), (PAD, PAD), (0, 0)), mode='symmetric')).save(W/'in/t.png')
subprocess.run([str(ESR), '-i', str(W/'in'), '-o', str(W/'out'), '-n', 'realesrgan-x4plus-anime', '-s', '4', '-f', 'png'], check=True, capture_output=True)
up = Image.open(W/'out/t.png').convert('RGB').crop((PAD*4, PAD*4, PAD*4+w*4, PAD*4+h*4))
tex = Image.merge('RGBA', (*up.split(), src.split()[3].resize(up.size, Image.BICUBIC)))
tex.save(W/'final.png'); tw, th = tex.size

def tr(p):   # NL (x right, y up, z front) -> GC body joint (X up, Y width, Z depth), right-handed
    return ((p[1]-P[:, 1].min())*S-419.0, p[0]*S*(-FRONT), p[2]*S*FRONT)

out = ['/* Generated by generate_gyroid.py from New Leaf int_hnw_ugaiM (disabled: GC gyroid kept, see generate_gyroid_hd.py). */', 'int g_pc_gyroid = 0;']
data = bytearray()
for ty in range(0, th, 4):
    for tx in range(0, tw, 4):
        tile = [tex.getpixel((tx+x, ty+y)) for y in range(4) for x in range(4)]
        data.extend(c for r, g, b, a in tile for c in (a, r)); data.extend(c for r, g, b, a in tile for c in (g, b))
out.append('static u8 pc_gyroid_tex[] ATTRIBUTE_ALIGN(32) = {'); out.extend(','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32)); out.append('};')
out.append('static const PC_TreeSourceLight pc_gyroid_light[] = {')
for v in vs:
    n = np.array(v['normal'], float); n /= np.linalg.norm(n) or 1
    out.append('{{%s},{255,255,255,255}},' % ','.join('%.5ff' % c for c in n))
out.append('};'); out.append('static Vtx pc_gyroid_v[] ATTRIBUTE_ALIGN(32) = {')
for v in vs:
    x, y, z = tr(v['position']); u, t = v['uv']
    out.append('{{{%d,%d,%d},0,{%d,%d},{255,255,255,255}}},' % (round(x), round(y), round(z), round(u*tw*32), round((1-t)*th*32)))
out.append('};')
dl = ['static Gfx pc_gyroid_dl[] = {', 'gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),', 'gsDPSetPrimColor(0,128,255,255,255,255),',
      'gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,0,0,0,COMBINED),',
      'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_OPA_SURF2),',
      f'gsDPSetTextureImage_Dolphin(G_IM_FMT_RGBA,G_IM_SIZ_32b,{tw},{th},pc_gyroid_tex),',
      'gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE,0,0,GX_MIRROR,GX_MIRROR,0,0),',
      'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_CULL_BACK|G_FOG|G_SHADING_SMOOTH),']
for base in range(0, len(vs), 30):
    c = min(30, len(vs)-base)
    dl.append(f'gsSPVertex(&pc_gyroid_v[{base}],{c},0),')
    for k in range(0, c, 3): dl.append(f'gsSP1Triangle({k},{k+1},{k+2},0),')
dl += ['gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_CULL_BACK|G_FOG|G_LIGHTING|G_SHADING_SMOOTH),', 'gsSPEndDisplayList(),', '};']
out += dl
out += ['Gfx* pc_gyroid_body(void) {', '    static unsigned generation;', '    if (!g_pc_gyroid) return NULL;',
        f'    if (generation != pc_tree_light_generation) {{ pc_tree_light_vertices(pc_gyroid_v,pc_gyroid_light,{len(vs)}); generation = pc_tree_light_generation; }}',
        '    return pc_gyroid_dl;', '}']
(ROOT/'ACGC-PC-Port/pc/src/pc_gyroid.c_inc').write_text('\n'.join(out)+'\n')
print('gyroid tris', len(vs)//3, 'scale', round(S, 1), 'texture', tex.size)
