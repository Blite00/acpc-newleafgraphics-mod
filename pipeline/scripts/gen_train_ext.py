"""Widescreen: continue the intro train car (rom_train_in) past its rear end, toward the camera.

The car model ends at z=5760 where the 4:3 camera never looks past; a wide view sees outside the car. This writes
src/data/field/bg/acre/rom_train_in/pc_train_ext.c_inc: side walls, roof and floor continued with the car's own textures,
UV rates and baked vertex shading (all read off rom_train_in_v), appended to rom_train_in_model.
"""
from pathlib import Path
EXT = 7000
Z0 = 5760; Z1 = Z0 + EXT
R = 2048/960.0                    # uv per world unit along the wall / roof (wall u and roof v run -6144 at z=5760)
def uz(z): return round(-6144 - R*(z - Z0))
def vf(z): return round(2048 - 3.2*(z - Z0))
out = ['/* Generated by gen_train_ext.py: the intro train car continued toward the camera for wide windows. */']
def vt(x, y, z, u, v, c): return '{{{%d,%d,%d},0,{%d,%d},{%d,%d,%d,255}}},' % (x, y, z, u, v, *c)
W = {640: (255, 255, 255), 1120: (230, 220, 255), 1920: (190, 180, 220), 2240: (140, 130, 200)}
# wall1: y 640 / 1120 / 1920, both sides; (y, v)
lo = [(640, 2048), (1120, 1024), (1920, 0)]
v1 = []; t1 = []
for x in (960, 3520):
    base = len(v1)
    for y, v in lo:
        for z in (Z0, Z1): v1.append(vt(x, y, z, uz(z), v, W[y]))
    # strips (y0,y1) x (z0,z1): verts index base + row*2 + col
    for r in range(2):
        a = base + r*2; b = a + 1; c = a + 2; d = a + 3
        t1 += [(a, b, d), (a, d, c)] if x == 960 else [(a, d, b), (a, c, d)]
v2 = []; t2 = []
for x in (960, 3520):
    base = len(v2)
    for y, v in ((1920, 0), (2240, 512)):
        for z in (Z0, Z1): v2.append(vt(x, y, z, uz(z), v, W[y]))
    a = base
    t2 += [(a, a+1, a+3), (a, a+3, a+2)] if x == 960 else [(a, a+3, a+1), (a, a+2, a+3)]
prof = [(960, 2240, -2048, (140, 130, 200)), (1600, 2480, -1024, (230, 220, 255)), (2240, 2560, 0, (255, 255, 255)),
        (2880, 2480, 1024, (230, 220, 255)), (3520, 2240, 2048, (140, 130, 200))]
v3 = []; t3 = []
for x, y, u, c in prof:
    for z in (Z0, Z1): v3.append(vt(x, y, z, u, uz(z), c))
for i in range(4):
    a = i*2
    t3 += [(a, a+1, a+3), (a, a+3, a+2)]
fl = [(960, 0, (190, 180, 220)), (2240, 4096, (255, 255, 255)), (3520, 8192, (190, 180, 220))]
v4 = []; t4 = []
for x, u, c in fl:
    for z in (Z0, Z1): v4.append(vt(x, 640, z, u, vf(z), c))
for i in range(2):
    a = i*2
    t4 += [(a, a+1, a+3), (a, a+3, a+2)]
for name, v in (('w1', v1), ('w2', v2), ('roof', v3), ('floor', v4)):
    out.append(f'static Vtx pc_train_ext_{name}_v[] ATTRIBUTE_ALIGN(32) = {{'); out += v; out.append('};')
def tris(name, n, t):
    out.append(f'gsSPVertex(pc_train_ext_{name}_v,{n},0),')
    out.extend(f'gsSP1Triangle({a},{b},{c},0),' for a, b, c in t)
out += ['Gfx pc_train_ext[] = {',
        'gsSPTexture(0, 0, 0, 0, G_ON),',
        'gsDPSetCombineLERP(TEXEL0, 0, SHADE, 0, 0, 0, 0, TEXEL0, PRIMITIVE, 0, COMBINED, 0, 0, 0, 0, COMBINED),',
        'gsDPSetRenderMode(G_RM_FOG_SHADE_A, G_RM_AA_ZB_TEX_EDGE2),',
        'gsDPLoadTLUT_Dolphin(15, 16, 1, rom_train_2_pal),',
        'gsSPLoadGeometryMode(G_ZBUFFER | G_SHADE | G_FOG | G_SHADING_SMOOTH),',
        'gsDPLoadTextureBlock_4b_Dolphin(rom_train_wall1_tex, G_IM_FMT_CI, 64, 64, 15, GX_MIRROR, GX_CLAMP, 0, 0),']
tris('w1', len(v1), t1)
out.append('gsDPLoadTextureBlock_4b_Dolphin(rom_train_wall2_tex, G_IM_FMT_CI, 64, 64, 15, GX_MIRROR, GX_MIRROR, 0, 0),')
tris('w2', len(v2), t2)
out.append('gsDPLoadTextureBlock_4b_Dolphin(rom_train_roof_tex, G_IM_FMT_CI, 64, 64, 15, GX_MIRROR, GX_REPEAT, 0, 0),')
tris('roof', len(v3), t3)
out.append('gsDPLoadTextureBlock_4b_Dolphin(rom_train_floor_tex, G_IM_FMT_CI, 64, 64, 15, GX_REPEAT, GX_REPEAT, 0, 0),')
tris('floor', len(v4), t4)
out += ['gsSPEndDisplayList(),', '};']
Path(__file__).resolve().parent.joinpath('ACGC-PC-Port/src/data/field/bg/acre/rom_train_in/pc_train_ext.c_inc').write_text('\n'.join(out)+'\n')
print('ok')
