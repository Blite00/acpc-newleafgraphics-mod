"""New Leaf dig clump (cg_grd_soil t_scoop / t_scoop_sand: one turf block with grass top and soil sides, or a sand block)
in place of the GC flat earth-chip billboards thrown by ef_dig_mud. One block centred on the origin, flat normals,
lit by the game's lights. Output: src/effect/pc_dig_clump.c_inc -> pc_dig_clump_dl(kind) kind 0 soil 1 sand 2 snow.
"""
import json
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent
SRC = ROOT/'dig_source/soil'
SCALE = 66.0           # NL block ~10.6 wide -> ~7 GC world units at the effect's 0.01 scale

def block(name, texname_filter=None):
    d = json.load(open(SRC/f'{name}.json'))
    tris = []
    for m in d['meshes']:
        vs = m['vertices']
        for i in range(0, len(vs), 3):
            t = vs[i:i+3]
            cx = np.mean([v['position'][0] for v in t])
            if -6.5 < cx < 6.5:                               # the middle block of the three
                tris.append((m['texture'], t))
    return tris

def centre(tris):
    P = np.array([v['position'] for _, t in tris for v in t])
    return (P.min(0)+P.max(0))/2

def gx_rgba8(name, im, out):
    im = im.convert('RGBA'); w, h = im.size; data = bytearray()
    for ty in range(0, h, 4):
        for tx in range(0, w, 4):
            tile = [im.getpixel((tx+x, ty+y)) for y in range(4) for x in range(4)]
            data.extend(cc for r, g, b, a in tile for cc in (a, r)); data.extend(cc for r, g, b, a in tile for cc in (g, b))
    out.append(f'static u8 {name}[] ATTRIBUTE_ALIGN(32) = {{')
    out.extend(','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32)); out.append('};')

def tex_soil_side():
    # NL m_block: constant2 (dark brown) -> constant1 (soil) by the grey side texture
    g = np.asarray(Image.open(SRC/'tex_side.png').convert('RGB')).astype(float).mean(-1, keepdims=True)/255
    lo, hi = np.array([87.0, 33, 0]), np.array([209.0, 181, 127])
    c = lo+(hi-lo)*np.clip(g*1.15, 0, 1)
    return Image.fromarray(np.dstack([c, np.full(g.shape, 255.0)]).astype(np.uint8), 'RGBA')
def tex_grass(snow=False):
    a = np.asarray(Image.open(SRC/'tex_grass.png').convert('RGBA')).astype(float)
    rgb = a[..., :3]
    if snow:
        lum = rgb.mean(-1, keepdims=True)
        rgb = np.clip(225+(lum-lum.mean())*0.25, 0, 255)*np.array([0.97, 0.98, 1.0])
    return Image.fromarray(np.dstack([np.clip(rgb, 0, 255), np.full(rgb.shape[:2]+(1,), 255.0)]).astype(np.uint8), 'RGBA')
def tex_sand():
    g = np.asarray(Image.open(SRC/'tex_sand00.png').convert('RGB')).astype(float).mean(-1, keepdims=True)/137
    c = np.clip(g*np.array([226.0, 204, 150]), 0, 255)
    return Image.fromarray(np.dstack([c, np.full(g.shape, 255.0)]).astype(np.uint8), 'RGBA')

out = ['/* Generated by generate_dig_clump.py: New Leaf dig clumps (t_scoop / t_scoop_sand). */']
TEX = {'side': tex_soil_side(), 'grass': tex_grass(False), 'snow': tex_grass(True), 'sand': tex_sand()}
for k, im in TEX.items(): gx_rgba8(f'pc_clump_tex_{k}', im, out)

def emit(prefix, tris, ctr):
    groups = {}
    for tx, t in tris: groups.setdefault(tx, []).append(t)
    names = []
    for tx, ts in groups.items():
        vname = f'{prefix}_{tx}_v'; names.append((tx, vname, len(ts)))
        out.append(f'static Vtx {vname}[] ATTRIBUTE_ALIGN(32) = {{')
        for t in ts:
            P = [np.array(v['position'])-ctr for v in t]
            n = np.cross(P[1]-P[0], P[2]-P[0]); n = n/max(np.linalg.norm(n), 1e-9)
            nb = ','.join(str(int(round(c*126)) & 255) for c in n)
            for v, p in zip(t, P):
                w, h = TEX['side'].size if tx == 'tex_side' else TEX['grass'].size if tx == 'tex_grass' else TEX['sand'].size
                out.append('{{{%d,%d,%d},0,{%d,%d},{%s,255}}},' % (round(p[0]*SCALE), round(p[1]*SCALE), round(p[2]*SCALE),
                           round(v['uv'][0]*w*32), round((1-v['uv'][1])*h*32), nb))
        out.append('};')
    return names

def dl(name, parts):
    global out
    out.append(f'static Gfx {name}[] = {{')
    out += ['gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),', 'gsDPSetPrimColor(0,128,255,255,255,255),',
            'gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,0,0,0,COMBINED),',
            'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_OPA_SURF2),',
            'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_FOG|G_LIGHTING|G_SHADING_SMOOTH),']
    for texsym, w, h, vname, ntri in parts:
        out += [f'gsDPSetTextureImage_Dolphin(G_IM_FMT_RGBA,G_IM_SIZ_32b,{w},{h},{texsym}),',
                'gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE,0,0,GX_REPEAT,GX_REPEAT,0,0),']
        n = ntri*3
        for base in range(0, n, 30):
            k = min(30, n-base); out.append(f'gsSPVertex(&{vname}[{base}],{k},0),')
            out += [f'gsSP1Triangle({j},{j+1},{j+2},0),' for j in range(0, k, 3)]
    out += ['gsSPEndDisplayList(),', '};']

soil = block('t_scoop'); c1 = centre(soil)
sn = emit('pc_clump_soil', soil, c1)
parts = []
for tx, vn, nt in sn:
    t = 'side' if tx == 'tex_side' else 'grass'
    parts.append((f'pc_clump_tex_{t}', *TEX[t].size, vn, nt))
dl('pc_clump_soil_dl', parts)
parts2 = [(p[0].replace('grass', 'snow'), *p[1:]) if 'grass' in p[0] else p for p in parts]
dl('pc_clump_snow_dl', parts2)
sand = block('t_scoop_sand'); c2 = centre(sand)
sn2 = emit('pc_clump_sand', sand, c2)
dl('pc_clump_sand_dl', [('pc_clump_tex_sand', *TEX['sand'].size, vn, nt) for _, vn, nt in sn2])
out += ['Gfx* pc_dig_clump_dl(int kind) { return kind == 1 ? pc_clump_sand_dl : kind == 2 ? pc_clump_snow_dl : pc_clump_soil_dl; }']
(ROOT/'ACGC-PC-Port/src/effect/pc_dig_clump.c_inc').write_text('\n'.join(out)+'\n')
print('ok', len(soil), len(sand))
