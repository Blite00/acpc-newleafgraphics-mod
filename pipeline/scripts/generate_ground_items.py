"""Original 3DS ground-item models (FgItemOutside.bcres) for native dropped items.

The native item ID still decides everything about the item; only the model
drawn on the ground changes. Items with no matching New Leaf ground model
(fish, tickets, exercise cards, pinwheel, fan, signboard, knife and fork)
stay native. The source export has no normals, so smooth normals are rebuilt
from the original geometry; positions, UVs and vertex colors are unchanged.
"""
import json
from collections import defaultdict
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent
SRC = ROOT/'tree_source/outside'
SCALE = 12243/83.0161  # shared donor-to-world scale (trees, plants)

def gx_rgba8(im):
    w, h = im.size; data = bytearray()
    for ty in range(0, h, 4):
        for tx in range(0, w, 4):
            tile = [im.getpixel((tx+x, ty+y)) for y in range(4) for x in range(4)]
            data.extend(c for r, g, b, a in tile for c in (a, r)); data.extend(c for r, g, b, a in tile for c in (g, b))
    return data

# Donor model per kind. Order defines the kind numbers used in C below.
KINDS = ['apple', 'orange', 'peach', 'pear', 'cherry', 'mush0', 'kabu', 'moneybag', 'leaf', 'map', 'paperbag',
         'present', 'seed', 'haniwa', 'fossil', 'can', 'boot', 'tire', 'letter', 'seedpitfall', 'bivalve', 'conch',
         'coral', 'candy', 'coconut', 'omikuji', 'cloth', 'carpet', 'wall', 'toolbox_E', 'toolbox_A', 'toolbox_B',
         'toolbox_D', 'G_toolbox_E', 'G_toolbox_A', 'G_toolbox_B', 'G_toolbox_D', 'umbrella', 'paper', 'paperbag_y',
         'music', 'bone', 'book', 'cage', 'seedling', 'seedling_c']
K = {n: i for i, n in enumerate(KINDS)}

out = ['/* Generated by generate_ground_items.py from original FgItemOutside.bcres. */', 'int g_pc_ground_items = 1;']
atlases = {}
for name in ('t_fg_outside', 't_fg_outside_2'):
    im = Image.open(SRC/(name+'.png')).convert('RGBA'); atlases[name] = im.size
    out.append(f'static u8 pc_gi_{name}[] ATTRIBUTE_ALIGN(32) = {{')
    data = gx_rgba8(im)
    out.extend(','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32))
    out.append('};')

counts = []
for kind, donor in enumerate(KINDS):
    meshes = json.loads((SRC/f'fg_{donor}_out.json').read_text())['meshes']
    vs = [dict(v, texture=m['texture']) for m in meshes for v in m['vertices']]
    assert len({m['texture'] for m in meshes}) == 1, donor
    tex = meshes[0]['texture']; w, h = atlases[tex]
    # Smooth normals from the original faces, shared by identical positions.
    acc = defaultdict(lambda: [0.0, 0.0, 0.0])
    for i in range(0, len(vs), 3):
        a, b, c = [v['position'] for v in vs[i:i+3]]
        u = [b[k]-a[k] for k in range(3)]; t = [c[k]-a[k] for k in range(3)]
        n = [u[1]*t[2]-u[2]*t[1], u[2]*t[0]-u[0]*t[2], u[0]*t[1]-u[1]*t[0]]
        for v in (a, b, c):
            s = acc[tuple(round(x, 4) for x in v)]
            for k in range(3): s[k] += n[k]
    counts.append(len(vs))
    out.append(f'static const PC_TreeSourceLight pc_gi_{kind}_light[] = {{')
    for v in vs:
        n = acc[tuple(round(x, 4) for x in v['position'])]; length = sum(c*c for c in n)**.5 or 1
        n = [c/length for c in n] if length > 1e-9 else [0, 1, 0]
        out.append('{{%s},{%s}},' % (','.join('%.6ff' % c for c in n), ','.join(str((v['color'] >> b) & 255) for b in (16, 8, 0, 24))))
    out.append('};')
    out.append(f'static Vtx pc_gi_{kind}_v[] ATTRIBUTE_ALIGN(32) = {{')
    for v in vs:
        x, y, z = [round(c*SCALE) for c in v['position']]
        u, t = v['uv']; u = round(u*w*32); t = round((1-t)*h*32)
        out.append('{{{%d,%d,%d},1,{%d,%d},{%s}}},' % (x, y, z, u, t, ','.join(str((v['color'] >> s) & 255) for s in (16, 8, 0, 24))))
    out += ['};', f'static Gfx pc_gi_{kind}_dl[] = {{', 'gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),',
            'gsDPSetTexEdgeAlpha(78),', 'gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,0,0,0,COMBINED),',
            f'gsDPSetTextureImage_Dolphin(G_IM_FMT_RGBA,G_IM_SIZ_32b,{w},{h},pc_gi_{tex}),',
            'gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE,0,0,GX_MIRROR,GX_MIRROR,0,0),',
            'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_CULL_BACK|G_FOG|G_SHADING_SMOOTH|G_DECAL_LEQUAL),',
            'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_TEX_EDGE2),']
    for base in range(0, len(vs), 30):
        count = min(30, len(vs)-base)
        out.append(f'gsSPVertex(&pc_gi_{kind}_v[{base}],{count},0),')
        idx = list(range(count)); out.append('gsSPNTrianglesInit_5b(%d,%s),' % (count//3, ','.join(map(str, (idx+[0]*9)[:9]))))
        for i in range(9, count, 12): out.append('gsSPNTriangles_5b(%s),' % ','.join(map(str, (idx[i:i+12]+[0]*12)[:12])))
    out += ['gsDPPipeSync(),', 'gsDPSetTexEdgeAlpha(144),',
            'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_CULL_BACK|G_FOG|G_LIGHTING|G_SHADING_SMOOTH|G_DECAL_LEQUAL),',
            'gsSPEndDisplayList(),', '};']
N = len(KINDS)
out += ['Gfx* pc_ground_item_mesh(int kind) {',
        'static Gfx* lists[]={'+','.join(f'pc_gi_{i}_dl' for i in range(N))+'};',
        'static Vtx* vertices[]={'+','.join(f'pc_gi_{i}_v' for i in range(N))+'};',
        'static const PC_TreeSourceLight* source[]={'+','.join(f'pc_gi_{i}_light' for i in range(N))+'};',
        'static const int counts[]={'+','.join(map(str, counts))+'};', f'static unsigned generations[{N}];',
        f'if(kind<0 || kind>={N}) return NULL;',
        'if(generations[kind]!=pc_tree_light_generation) { pc_tree_light_vertices(vertices[kind],source[kind],counts[kind]); generations[kind]=pc_tree_light_generation; }',
        'return lists[kind];', '}']
(ROOT/'ACGC-PC-Port/pc/src/pc_ground_items.c_inc').write_text('\n'.join(out)+'\n')

# Native item -> kind. mNT_get_itemTableNo supplies the original item type.
T = {'APPLE': 'apple', 'ORANGE': 'orange', 'PEACH': 'peach', 'PEAR': 'pear', 'NUTS': 'cherry', 'MATSUTAKE': 'mush0',
     'KABU': 'kabu', 'BAG': 'moneybag', 'LEAF': 'leaf', 'ROLL': 'map', 'PACK': 'paperbag', 'PRESENT': 'present',
     'HANIWA': 'haniwa', 'FOSSIL': 'fossil', 'LETTER': 'letter', 'OTOSI': 'seedpitfall', 'SHELLA': 'bivalve',
     'SHELLB': 'conch', 'SHELLC': 'coral', 'CANDY': 'candy', 'COCONUT': 'coconut', 'OMIKUJI': 'omikuji',
     'CLOTH': 'cloth', 'CARPET': 'carpet', 'WALL': 'wall', 'AXE': 'toolbox_E', 'NET': 'toolbox_A', 'ROD': 'toolbox_B',
     'SHOVEL': 'toolbox_D', 'AXE2': 'G_toolbox_E', 'NET2': 'G_toolbox_A', 'ROD2': 'G_toolbox_B', 'SHOVEL2': 'G_toolbox_D',
     'UMBRELLA': 'umbrella', 'PAPER': 'paper', 'FLOWER_SEED': 'seed', 'HUKUBUKURO': 'paperbag_y', 'MD': 'music',
     'BONE': 'bone', 'DIARY': 'book', 'CAGE': 'cage'}
cases = [f'        case mNT_ITEM_TYPE_{t}: return {K[d]};' for t, d in T.items()]
h = ['/* Generated by generate_ground_items.py: native item -> New Leaf ground model. */',
     '#ifndef PC_GROUND_ITEM_ROUTES_H', '#define PC_GROUND_ITEM_ROUTES_H', '#include "m_name_table.h"',
     'static int pc_ground_item_kind(mActor_name_t item) {',
     '    switch (item) {',
     f'        case ITM_DUST0_EMPTY_CAN: return {K["can"]};', f'        case ITM_DUST1_BOOT: return {K["boot"]};',
     f'        case ITM_DUST2_OLD_TIRE: return {K["tire"]};', f'        case ITM_CEDAR_SAPLING: return {K["seedling_c"]};',
     f'        case ITM_SAPLING: return {K["seedling"]};', '        default: break;', '    }',
     '    switch (mNT_get_itemTableNo(item)) {'] + cases + ['        default: return -1;', '    }', '}', '#endif']
(ROOT/'ACGC-PC-Port/pc/include/pc_ground_item_routes.h').write_text('\n'.join(h)+'\n')
mats = ['apple_DL_mode', 'orange_DL_mode', 'peach_DL_mode', 'pear_DL_mode', 'nuts_DL_mode', 'matutake_DL_mode',
        'kabu_DL_mode', 'bag_DL_mode', 'leaf_DL_mode', 'obj_rollT_mat_model', 'box_DL_mode', 'pack_DL_mode',
        'present_DL_mode', 'seed_DL_mode', 'obj_haniwaT_mat_model', 'obj_boxT_mat_model', 'obj_fossilT_mat_model',
        'obj_trashT_mat_model', 'obj_otosiT_mat_model', 'obj_item_shellAT_mat_model', 'obj_item_shellBT_mat_model',
        'obj_item_shellCT_mat_model', 'obj_shop_candy_mat_modelT', 'obj_item_cocoT_mat_model', 'obj_item_clothT_mat_model',
        'obj_item_carpetT_mat_model', 'obj_item_wallT_mat_model', 'obj_item_axeT_mat_model', 'obj_item_netT_mat_model',
        'obj_item_rodT_mat_model', 'obj_item_shovelT_mat_model', 'obj_item_axe2T_mat_model', 'obj_item_net2T_mat_model',
        'obj_item_rod2T_mat_model', 'obj_item_shovel2T_mat_model', 'obj_item_umbrellaT_mat_model',
        'obj_item_paperT_mat_model', 'obj_item_seedT_mat_model', 'obj_item_fukuT_mat_model', 'obj_mdT_mat_model',
        'obj_item_boneT_mat_model', 'obj_item_diaryT_mat_model']
h2 = ['/* Native ground-item materials eligible for New Leaf models. */', '#ifndef PC_GROUND_ITEM_MATS_H', '#define PC_GROUND_ITEM_MATS_H']
h2 += [f'extern Gfx {m}[];' for m in mats]
h2 += ['static int pc_ground_item_material(Gfx* material) {', '    static Gfx* const mats[] = {'+','.join(mats)+'};',
       '    unsigned i;', '    for (i = 0; i < sizeof(mats)/sizeof(mats[0]); i++) if (mats[i] == material) return 1;', '    return 0;', '}', '#endif']
(ROOT/'ACGC-PC-Port/pc/include/pc_ground_item_mats.h').write_text('\n'.join(h2)+'\n')
print('kinds', N, 'atlases', atlases)
