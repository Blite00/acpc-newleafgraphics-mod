"""Rover's intro lines for the character creator, encoded in the game's message format.

0x2AD6 / 0x2AD7 (after "isn't it cool / cute?") keep the name reply but drop the boy/girl guess, and end with
Rover asking what the player looks like (order 9 = 1 tells the guide to open the creator).
0x2AD8 / 0x2AD9 (the lines after the creator, guide / guide2) get "Ah, there you are!" in front.
Output: pc/src/pc_nl_creator_msgs.c_inc (included by pc_nl_creator.c).

Shippable version: the original GameCube lines are read from the player's own disc (chr_work/arc/message_data.bin);
only our edits live here, applied by line position and control code.
"""
import struct, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT/'ACGC-PC-Port/tools'))
import msg_tool as mt

LOOK = ("Say,<<PAUSE [06]>> the sun's right in my\n"
        "eyes...<<PAUSE [08]>> I can't quite make\n"
        "you out, <<STR_PLAYERNAME>>.<<PAUSE [08]>>\n"
        "What do you look like, anyway?\n"
        "<<DEMONPC0 [09 00 01]>>\n<<BTN2>>\n<<MSGCONTINUE>>")
PREFIX = ("<<DEMONPC0 [00 00 18]>>Ah, there you are!<<PAUSE [08]>>\n"
          "Nice to meet you, <<STR_PLAYERNAME>>!<<BTN>>\n"
          "<<DEMONPC0 [00 00 FE]>>\n<<MSGCLEAR>>")
# entry: (lines to replace (first, count) -> our line, control code where the original ending starts, our ending)
EDITS = {
    0x2AD6: ((2, 1), "It's a really cool name!<<PAUSE [06]>>", '<<DEMONPC0 [09 00 01]>>',
             "<<BTN>>\n<<DEMONPC0 [00 00 FE]>>\n<<MSGCLEAR>>"),
    0x2AD7: ((2, 2), "It's a very cute name!<<BTN>>", '<<DEMONPC0 [09 00 02]>>', "<<BTN>>\n<<MSGCLEAR>>"),
}


def original(idx):
    arc = ROOT / 'chr_work' / 'arc'
    data = bytearray((arc / 'message_data.bin').read_bytes())
    table = (arc / 'message_data_table.bin').read_bytes()
    ends = struct.unpack('>%dI' % (len(table) // 4), table)
    s = mt.decode_entry(data, ends[idx - 1] if idx else 0, ends[idx], idx)
    return s[s.index('START]]\n') + len('START]]\n'):].rstrip('\n')


def edited(idx):
    (first, count), line, cut, ending = EDITS[idx]
    s = original(idx)
    s = s[:s.index(cut)]
    lines = s.split('\n')
    lines[first:first + count] = [line]
    return '\n'.join(lines) + ending + LOOK


def carr(name, b):
    return f'static const u8 {name}[{len(b)}] = {{ ' + ','.join(map(str, b)) + ' };'


def main():
    out = ['/* Generated by generate_nl_creator_msgs.py */']
    for k in EDITS:
        out.append(carr(f'pc_cc_msg_{k:04X}', mt.encode_entry(edited(k))))
    out.append(carr('pc_cc_msg_prefix', mt.encode_entry(PREFIX)))
    (ROOT/'ACGC-PC-Port/pc/src/pc_nl_creator_msgs.c_inc').write_text('\n'.join(out)+'\n')
    print('ok')


if __name__ == '__main__':
    main()
