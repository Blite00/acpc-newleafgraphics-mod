"""Adapt the donor tree to the existing town and interaction draw paths."""
import json
from PIL import Image
from pathlib import Path
ROOT = Path(__file__).resolve().parent
vs = json.loads((ROOT/'tree_source/season08_normals/fg_treeA_4.json').read_text())['meshes'][0]['vertices']
scale = 12243 / max(v['position'][1] for v in vs)
parts = {'leaf': [], 'trunk': []}
for i in range(0, len(vs), 3):
    tri = vs[i:i+3]
    # Bark occupies the lower-right atlas rectangle. Other leaf patches
    # extend below V=.53 on the left, so V alone cannot classify them.
    # This donor mesh stores the 79 connected bark triangles first;
    # later leaves can reuse this rectangle through mirrored wrapping.
    bark = i < 79 * 3
    if bark:
        assert all(v['uv'][1] < .53 and .5 < v['uv'][0] <= 1.01 for v in tri)
    parts['trunk' if bark else 'leaf'].extend(tri)
assert len(parts['trunk']) == 79 * 3
assert sum(map(len,parts.values())) == 618
stump = json.loads((ROOT/'tree_source/season08_normals/fg_treeA_4_b.json').read_text())['meshes'][0]
assert stump['texture'] == 'treeA' and len(stump['vertices']) == 153
parts['stump'] = stump['vertices']
felled = json.loads((ROOT/'tree_source/animations_normals/fg_treeA_4_t.json').read_text())['meshes'][0]
assert felled['texture'] == 'treeA' and len(felled['vertices']) == 486
assert min(v['position'][1] for v in felled['vertices']) == 16
assert max(v['position'][1] for v in stump['vertices']) == 16
# The animated donor upper section has the same bind-pose triangles as the
# standing tree above its cut line, in a different order. Classify them by
# source geometry/UVs rather than guessing from their order or bone numbers.
def triangle_key(tri):
    return tuple(sorted(tuple(round(x,3) for x in v['position']) +
                        tuple(round(x,4) for x in v['uv']) for v in tri))
source_parts = {triangle_key(vertices[i:i+3]):part
                for part in ('leaf','trunk') for vertices in [parts[part]]
                for i in range(0,len(vertices),3)}
parts['felled_leaf'] = []
parts['felled_trunk'] = []
for i in range(0,len(felled['vertices']),3):
    tri=felled['vertices'][i:i+3]
    parts['felled_'+source_parts[triangle_key(tri)]].extend(tri)
assert len(parts['felled_leaf']) == 127*3
assert len(parts['felled_trunk']) == 35*3
out=['/* Generated by generate_tree_world.py; original donor colors and normals. */', '#include "m_common_data.h"']
# All donor seasons share the same hardwood topology, UVs, vertex colors and
# normals (checked below, including snow). Only the original atlas changes.
for season in range(23):
    folder=ROOT/f'tree_source/season{season:02}_normals'
    tree=json.loads((folder/'fg_treeA_4.json').read_text())['meshes'][0]['vertices']
    cut=json.loads((folder/'fg_treeA_4_b.json').read_text())['meshes'][0]['vertices']
    for current,reference in [(tree,vs),(cut,parts['stump'])]:
        assert len(current)==len(reference)
        assert all(all(a[k]==b[k] for k in ('position','uv','color','normal')) for a,b in zip(current,reference)),season
    atlas=Image.open(folder/'treeA.png').convert('RGBA')
    assert atlas.size==(128,256)
    tex=bytearray()
    for ty in range(0,256,4):
        for tx in range(0,128,4):
            tile=[atlas.getpixel((tx+x,ty+y)) for y in range(4) for x in range(4)]
            tex.extend(c for r,g,b,a in tile for c in (a,r))
            tex.extend(c for r,g,b,a in tile for c in (g,b))
    out += [f'static u8 pc_tree_season{season:02}_tex[] ATTRIBUTE_ALIGN(32) = {{']
    out += [','.join(map(str,tex[i:i+32]))+',' for i in range(0,len(tex),32)]
    out += ['};']
out += ['static u8* pc_tree_season_atlases[23] = {'+','.join(f'pc_tree_season{s:02}_tex' for s in range(23))+'};']
# Original treeA2 is the nonfruit hardwood atlas, including spring blossoms
# and its distinct autumn progression. Alias identical source images only.
hardwood_atlases=[]
for season in range(23):
    folder=ROOT/f'tree_source/season{season:02}_normals'
    atlas=Image.open(folder/'treeA2.png').convert('RGBA')
    original=Image.open(folder/'treeA.png').convert('RGBA')
    if atlas.tobytes()==original.tobytes():
        hardwood_atlases.append(f'pc_tree_season{season:02}_tex')
        continue
    name=f'pc_tree_hardwood{season:02}_tex'
    hardwood_atlases.append(name)
    assert atlas.size==(128,256)
    tex=bytearray()
    for ty in range(0,256,4):
        for tx in range(0,128,4):
            tile=[atlas.getpixel((tx+x,ty+y)) for y in range(4) for x in range(4)]
            tex.extend(c for r,g,b,a in tile for c in (a,r))
            tex.extend(c for r,g,b,a in tile for c in (g,b))
    out += [f'static u8 {name}[] ATTRIBUTE_ALIGN(32) = {{']
    out += [','.join(map(str,tex[i:i+32]))+',' for i in range(0,len(tex),32)]
    out += ['};']
out += ['static u8* pc_tree_hardwood_atlases[23] = {'+','.join(hardwood_atlases)+'};']

out += [
    '/* Exact donor season dispatch: loader 0x5f861c -> 0x5cc004,',
    ' * inclusive month/day end table at 0x931cc6. Ordinary town calendar. */',
    'static int pc_tree_world_season(void) {',
    '    static const unsigned short ends[23]={115,218,224,331,405,410,414,607,615,627,705,723,907,915,1016,1024,1101,1109,1117,1125,1130,1210,1231};',
    '    int md=Common_Get(time.rtc_time.month)*100+Common_Get(time.rtc_time.day);',
    '    int i; for(i=0;i<22 && md>ends[i];++i) {}',
    '    return i;',
    '}'
]
out += r"""
typedef struct { float normal[3]; unsigned char color[4]; } PC_TreeSourceLight;
static float pc_tree_ambient[3]={1,1,1}, pc_tree_sun[3], pc_tree_moon[3];
static float pc_tree_sun_direction[3], pc_tree_moon_direction[3];
static unsigned pc_tree_light_generation=1;
static int pc_tree_donor_enabled;
static float pc_tree_donor_diffuse[3],pc_tree_donor_specular[3];
static float pc_tree_donor_sky[3],pc_tree_donor_ground[3];
void pc_tree_world_set_donor_light(int enabled,const unsigned char* diffuse,
    const unsigned char* specular,const unsigned char* sky,const unsigned char* ground) {
    int c; pc_tree_donor_enabled=enabled;
    for(c=0;c<3;++c) {
        pc_tree_donor_diffuse[c]=diffuse[c]/255.0f;
        pc_tree_donor_specular[c]=specular[c]/255.0f;
        pc_tree_donor_sky[c]=sky[c]/255.0f;
        pc_tree_donor_ground[c]=ground[c]/255.0f;
    }
    ++pc_tree_light_generation;
}
void pc_tree_world_set_light(const unsigned char* ambient, const unsigned char* sun,
    const unsigned char* moon, float sx,float sy,float sz,float mx,float my,float mz) {
    float sl=sqrtf(sx*sx+sy*sy+sz*sz), ml=sqrtf(mx*mx+my*my+mz*mz);
    int i; if(sl<.001f) sl=1; if(ml<.001f) ml=1;
    pc_tree_sun_direction[0]=sx/sl; pc_tree_sun_direction[1]=sy/sl; pc_tree_sun_direction[2]=sz/sl;
    pc_tree_moon_direction[0]=mx/ml; pc_tree_moon_direction[1]=my/ml; pc_tree_moon_direction[2]=mz/ml;
    for(i=0;i<3;++i) {pc_tree_ambient[i]=ambient[i]/255.0f; pc_tree_sun[i]=sun[i]/255.0f; pc_tree_moon[i]=moon[i]/255.0f;}
    ++pc_tree_light_generation;
}
/* Apply live donor fragment diffuse/global ambient plus hemisphere when enabled. The donor
 * tree's view-dependent rim/specular LUT terms still require a separate shader;
 * storing their environment color does not claim those terms are reproduced.
 * Otherwise apply native ambient/directional lighting, preserving donor vertex
 * colors (normal and color share Vtx bytes). Animated parts use bind normals. */
static void pc_tree_light_vertices(Vtx* vertices,const PC_TreeSourceLight* source,int count) {
    int i,c; for(i=0;i<count;++i) {
        const float* n=source[i].normal;
        float ds=n[0]*pc_tree_sun_direction[0]+n[1]*pc_tree_sun_direction[1]+n[2]*pc_tree_sun_direction[2];
        float dm=n[0]*pc_tree_moon_direction[0]+n[1]*pc_tree_moon_direction[1]+n[2]*pc_tree_moon_direction[2];
        if(ds<0) ds=0; if(dm<0) dm=0;
        for(c=0;c<3;++c) {
            float light;
            if(pc_tree_donor_enabled) {
                /* Actual commonNW hemisphere axis/scale and m_treeA's
                 * additive fragment+vertex primary, multiplied by source AO.
                 * Source daily actor direction uses the unrolled world frame. */
                float hw=(n[1]*0.894427191f+n[2]*0.4472135955f)*0.5f+0.5f;
                float directional=n[0]*g_pc_donor_actor_direction[0]+
                                  n[1]*g_pc_donor_actor_direction[1]+
                                  n[2]*g_pc_donor_actor_direction[2];
                if(directional<0) directional=0;
                if(hw<0) hw=0; if(hw>1) hw=1;
                light=pc_tree_donor_diffuse[c]*directional+g_pc_donor_global_ambient[c]+
                      pc_tree_donor_ground[c]+(pc_tree_donor_sky[c]-pc_tree_donor_ground[c])*hw;
                light*=source[i].color[3]/255.0f;
            } else {
                light=pc_tree_ambient[c]+ds*pc_tree_sun[c]+dm*pc_tree_moon[c];
            }
            if(light>1) light=1; if(light<0) light=0;
            vertices[i].v.cn[c]=(unsigned char)(source[i].color[c]*light+0.5f);
        }
    }
}
""".splitlines()
# Preserve source front geometry and the existing planting depth.
from support_closure import support_closure, host_ground_support_depth
support_depth=host_ground_support_depth(ROOT)
rear_support=support_closure(parts['stump'],extra_depth=support_depth/(scale*0.01))
parts['trunk']=parts['trunk']+rear_support
parts['stump']=parts['stump']+rear_support
variants=[('leaf','leaf',None),('trunk','trunk',None),
          ('shake','leaf',(7000,0)),('cutL_leaf','felled_leaf',(7000,-1000)),
          ('cutR_leaf','felled_leaf',(7000,1000)),('cutL_trunk','felled_trunk',(2250,-1000)),
          ('cutR_trunk','felled_trunk',(2250,1000)),('stump','stump',None)]
for name, part, pivot in variants:
    vertices=parts[part]
    out.append('static const PC_TreeSourceLight pc_tw_%s_light[] = {'%name)
    for v in vertices:
        normal=v['normal']; length=sum(c*c for c in normal)**.5
        assert length>.9
        normal=[c/length for c in normal]
        color=[(v['color']>>b)&255 for b in (16,8,0,24)]
        out.append('{{%s},{%s}},'%(','.join('%.8ff'%c for c in normal),','.join(map(str,color))))
    out.append('};')
    out.append('static Vtx pc_tw_%s_v[] ATTRIBUTE_ALIGN(32) = {'%name)
    for v in vertices:
        x,y,z=[round(c*scale) for c in v['position']]
        if pivot: x,y=y-pivot[0],-x+pivot[1]
        u,t=v['uv']; u=round(u*128*32); t=round((1-t)*256*32)
        c=v['color']; rgba=[(c>>s)&255 for s in (16,8,0,24)]
        out.append('{{{%d,%d,%d},1,{%d,%d},{%s}}},'%(x,y,z,u,t,','.join(map(str,rgba))))
    out += ['};','static Gfx pc_tw_%s_dl[] = {'%name,
        'gsDPPipeSync(),','gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),',
        'gsDPSetTexEdgeAlpha(78),',
        ('gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,COMBINED,0,PRIM_LOD_FRAC,PRIMITIVE),' if pivot else
         'gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,0,0,0,COMBINED),'),
        'gsDPSetTextureImage_Dolphin(G_IM_FMT_RGBA,G_IM_SIZ_32b,128,256,pc_tree_preview_tex),',
        'gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE,0,0,GX_MIRROR,GX_MIRROR,0,0),',
        'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_FOG|G_SHADING_SMOOTH|G_DECAL_LEQUAL),']
    if pivot is None:
        out.append('gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_TEX_EDGE2),')
    for base in range(0,len(vertices),30):
        count=min(30,len(vertices)-base)
        out.append('gsSPVertex(&pc_tw_%s_v[%d],%d,0),'%(name,base,count))
        indices=list(range(count)); first=(indices+[0]*9)[:9]
        out.append('gsSPNTrianglesInit_5b(%d,%s),'%(count//3,','.join(map(str,first))))
        for i in range(9,count,12):
            batch=(indices[i:i+12]+[0]*12)[:12]
            out.append('gsSPNTriangles_5b(%s),'%','.join(map(str,batch)))
    out += ['gsDPPipeSync(),','gsDPSetTexEdgeAlpha(144),',
        'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_CULL_BACK|G_FOG|G_LIGHTING|G_SHADING_SMOOTH|G_DECAL_LEQUAL),',
        'gsSPEndDisplayList(),','};']
for name,_,_ in variants:
    out.append(f'static Gfx pc_tw_{name}_hardwood_dl[ARRAY_COUNT(pc_tw_{name}_dl)];')
out += ['Gfx* pc_tree_world_mesh_style(int part, int hardwood) {',
        'static Gfx* lists[] = {%s};'%','.join('pc_tw_'+n+'_dl' for n,_,_ in variants),
        'static Gfx* hardwood_lists[] = {%s};'%','.join('pc_tw_'+n+'_hardwood_dl' for n,_,_ in variants),
        'static const unsigned list_sizes[] = {%s};'%','.join('sizeof(pc_tw_'+n+'_dl)' for n,_,_ in variants),
        'static Vtx* vertices[] = {%s};'%','.join('pc_tw_'+n+'_v' for n,_,_ in variants),
        'static const PC_TreeSourceLight* source[] = {%s};'%','.join('pc_tw_'+n+'_light' for n,_,_ in variants),
        'static const int counts[] = {%s};'%','.join(str(len(parts[p])) for _,p,_ in variants),
        'static unsigned generations[8];',
        'if(part>=0 && part<8 && generations[part]!=pc_tree_light_generation) {',
        'pc_tree_light_vertices(vertices[part],source[part],counts[part]); generations[part]=pc_tree_light_generation;',
        '}',
        'if(part>=0 && part<8) {',
        '    int season=pc_tree_world_season();',
        '    if(hardwood) {',
        '        memcpy(hardwood_lists[part],lists[part],list_sizes[part]);',
        '        hardwood_lists[part][4].words.w1=_GBI_RUNTIME_PTR(pc_tree_hardwood_atlases[season]);',
        '        return hardwood_lists[part];',
        '    }',
        '    /* Entry4 is the image command; all23 source meshes/UVs were verified identical. */',
        '    lists[part][4].words.w1=_GBI_RUNTIME_PTR(pc_tree_season_atlases[season]);',
        '}',
        'return part >= 0 && part < 8 ? lists[part] : NULL;' , '}',
        'Gfx* pc_tree_world_mesh(int part) { return pc_tree_world_mesh_style(part,1); }' ]
(ROOT/'ACGC-PC-Port/pc/src/pc_tree_world.c_inc').write_text('\n'.join(out)+'\n')
print('World model triangles:', {p:len(v)//3 for p,v in parts.items()})
