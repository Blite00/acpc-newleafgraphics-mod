def _s2x(a):
    h, w = a.shape[:2]; Pp = np.pad(a, ((1, 1), (1, 1), (0, 0)), mode='edge')
    B, Dd, E, F, Hh = Pp[:-2, 1:-1], Pp[1:-1, :-2], Pp[1:-1, 1:-1], Pp[1:-1, 2:], Pp[2:, 1:-1]
    eq = lambda x, y: (np.abs(x-y).sum(-1) < 1)[..., None]
    c_ = eq(B, Hh) | eq(Dd, F)
    o = np.empty((h*2, w*2, a.shape[2])); o[0::2, 0::2] = np.where(~c_ & eq(Dd, B), Dd, E); o[0::2, 1::2] = np.where(~c_ & eq(B, F), F, E)
    o[1::2, 0::2] = np.where(~c_ & eq(Dd, Hh), Dd, E); o[1::2, 1::2] = np.where(~c_ & eq(Hh, F), F, E); return o
