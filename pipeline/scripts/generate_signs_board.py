def rgba8(name, im):
    im = im.convert('RGBA'); w, h = im.size; data = bytearray()
    for ty in range(0, h, 4):
        for tx in range(0, w, 4):
            tile = [im.getpixel((tx+x, ty+y)) for y in range(4) for x in range(4)]
            data.extend(c for r, g, b, a in tile for c in (a, r)); data.extend(c for r, g, b, a in tile for c in (g, b))
    out.append(f'static u8 {name}[] ATTRIBUTE_ALIGN(32) = {{'); out.extend(','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32)); out.append('};')

def nb(n):
    n = np.array(n, float); n /= max(np.linalg.norm(n), 1e-9)
    n = n*0.6+np.array([0, 0.6, 0]); n /= np.linalg.norm(n)       # lit from above like the native props
    return ','.join(str(int(round(c*126)) & 255) for c in n)

def vtx_array(name, verts, tw, th):
    """verts: list of (pos, uv(0..1, v up), normal); per-triangle whole-tile shift keeps s16 texcoords in range"""
    out.append(f'static Vtx {name}[] ATTRIBUTE_ALIGN(32) = {{')
    for i in range(0, len(verts), 3):
        tri = verts[i:i+3]
        su = 2*np.floor(min(v[1][0] for v in tri)/2); sv = 2*np.floor(min(v[1][1] for v in tri)/2)
        for p, uv, n in tri:
            out.append('{{{%d,%d,%d},0,{%d,%d},{%s,255}}},' % (round(p[0]), round(p[1]), round(p[2]),
                       round((uv[0]-su)*tw*32), round((1-(uv[1]-sv))*th*32), nb(n)))
    out.append('};')

def tri_cmds(name, count):
    c = []
    for base in range(0, count, 30):
        k = min(30, count-base); c.append(f'gsSPVertex(&{name}[{base}],{k},0),')
        c += [f'gsSP1Triangle({j},{j+1},{j+2},0),' for j in range(0, k, 3)]
    return c

