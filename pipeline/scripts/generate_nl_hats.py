"""New Leaf hats for the GameCube player (a PC appearance setting; the GC game has no hats).

Every New Leaf cap_* model becomes a display list in New Leaf head space (x100, so the coordinates keep their
precision as integers); pc_nl_heads draws it on the head joint through a per-gender scale/offset matrix, the same
fit the New Leaf heads use. Meshes that New Leaf draws with generated texture coordinates (reflection/sphere maps)
are left out; alpha-tested meshes are drawn as cut-outs.

Output: pc/src/pc_nl_hats_<k>.c (split for the compiler) + pc_nl_hats.c with the table:
    int pc_nl_hat_count; Gfx* pc_nl_hat_dl[]; const char* pc_nl_hat_name[]
"""
import json, re
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent
SRC = ROOT/'hat_source'
OUTDIR = ROOT/'ACGC-PC-Port/pc/src'
K = 100.0
CHUNK = 2_000_000
WRAP = {0: 'GX_CLAMP', 1: 'GX_CLAMP', 2: 'GX_REPEAT', 3: 'GX_MIRROR'}
HEAD = ['/* Generated by generate_nl_hats.py: New Leaf hats. */', '#include "pc_platform.h"', '#include "PR/mbi.h"',
        '#include "libultra/libultra.h"', '#include "libforest/gbi_extensions.h"', '']

def rgba8(name, im, out):
    w, h = im.size; data = bytearray()
    for ty in range(0, h, 4):
        for tx in range(0, w, 4):
            tile = [im.getpixel((tx+x, ty+y)) for y in range(4) for x in range(4)]
            data.extend(cc for r, g, b, a in tile for cc in (a, r)); data.extend(cc for r, g, b, a in tile for cc in (g, b))
    out.append(f'static u8 {name}[] ATTRIBUTE_ALIGN(32) = {{')
    out.extend(','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32)); out.append('};')

MINX = {}
def hat(name):
    d = json.load(open(SRC/name/f'{name}.json'))
    MINX[name] = int(round(min(v['position'][0] for m in d['meshes'] for v in m['vertices'])*K))
    out = []; dl = [f'Gfx pc_nlhat_{name}[] = {{', 'gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),',
                    'gsDPSetPrimColor(0,128,255,255,255,255),',
                    'gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,0,0,0,COMBINED),']
    used = 0; glow = []
    for mi, m in enumerate(d['meshes']):
        if m['coordinator']['projection'] != 0: continue          # reflection / sphere-mapped layers
        if not m['texture']:
            glow.append((mi, m)); continue                         # colour-only glow shells, drawn last
        tex = SRC/name/f"{m['texture']}.png"
        if not tex.exists(): continue
        im = Image.open(tex).convert('RGBA'); tw, th = im.size
        env = [p for p in sorted((SRC/name).glob('*.png')) if p.stem not in {mm['texture'] for mm in d['meshes']}]
        # New Leaf alpha test (PICA functions): 1 = always passes, 6 = greater than the reference, ... A passing
        # texel is made fully opaque and a failing one clear, so the game's edge test reproduces it exactly
        at = m['alphaTest']
        cut = at['isTestEnabled'] and at['testFunction'] != 1
        a = np.array(im, float); A = a[..., 3].copy(); ref = at['testReference']
        if 'crown' in name and env:
            # crowns get their gold from New Leaf's sphere-mapped reflection layer, which is not drawn here; the base
            # texture's alpha above the cut is that layer's mask, so bake the reflection's average colour in
            gold = np.array(Image.open(env[0]).convert('RGB'), float).reshape(-1, 3).mean(0)
            if ref == 0:
                # the royal crown's unmasked parts are its red velvet and jewels (lit by NL's constant colours)
                under = np.array([215, 45, 30], float) if 'royal' in name else np.zeros(3)
                a[..., :3] += A[..., None]/255*gold+(1-A[..., None]/255)*under
            else:
                a[..., :3] = np.maximum(a[..., :3], [255, 222, 110])        # cut-out parts (the royal cross): bright gold
            a[..., :3] = np.clip(a[..., :3], 0, 255); a[..., 3] = 255
        if cut:
            ops = {0: A < -1, 2: A == ref, 3: A != ref, 4: A < ref, 5: A <= ref, 6: A > ref, 7: A >= ref}
            a[..., 3] = np.where(ops.get(at['testFunction'], A > ref), 255, 0)
        im = Image.fromarray(a.astype(np.uint8), 'RGBA')
        if tw % 4 or th % 4 or tw > 256 or th > 256: continue
        tname = f'pc_nlhat_{name}_{mi}_t'; vname = f'pc_nlhat_{name}_{mi}_v'
        rgba8(tname, im, out)
        wu, wv = m['mapper']['wrapU'], m['mapper']['wrapV']
        vs = m['vertices']
        out.append(f'static Vtx {vname}[] ATTRIBUTE_ALIGN(32) = {{')
        for i in range(0, len(vs), 3):
            tri = vs[i:i+3]
            pu = 2 if wu == 3 else 1; pv = 2 if wv == 3 else 1
            su = pu*np.floor(min(v['uv'][0] for v in tri)/pu) if wu >= 2 else 0
            sv = pv*np.floor(min(v['uv'][1] for v in tri)/pv) if wv >= 2 else 0
            for v in tri:
                x, y, z = (int(round(c*K)) for c in v['position'])
                n = np.array(v['normal'], float); n /= max(np.linalg.norm(n), 1e-9)
                if 'crown' in name and cut and ref > 0:
                    n = np.array([1.0, 0, 0])      # the royal cross is a flat card: light it from above (head +x)
                out.append('{{{%d,%d,%d},0,{%d,%d},{%s,255}}},' % (x, y, z, round((v['uv'][0]-su)*tw*32),
                           round((1-(v['uv'][1]-sv))*th*32), ','.join(str(int(round(c*120)) & 255) for c in n)))
        out.append('};')
        dl += [f'gsDPSetRenderMode(G_RM_FOG_SHADE_A,{"G_RM_AA_ZB_TEX_EDGE2" if cut else "G_RM_AA_ZB_OPA_SURF2"}),',
               # crowns are open rings: their far panels' inner faces show through the top, as in New Leaf
               f'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|{"" if "crown" in name else "G_CULL_BACK|"}G_FOG|G_LIGHTING|G_SHADING_SMOOTH),',
               f'gsDPSetTextureImage_Dolphin(G_IM_FMT_RGBA,G_IM_SIZ_32b,{tw},{th},{tname}),',
               f'gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE,0,0,{WRAP[wu]},{WRAP[wv]},0,0),']
        for base in range(0, len(vs), 30):
            k = min(30, len(vs)-base); dl.append(f'gsSPVertex(&{vname}[{base}],{k},0),')
            dl += [f'gsSP1Triangle({j},{j+1},{j+2},0),' for j in range(0, k, 3)]
        used += 1
    # Untextured meshes (the glow_* hats' glowing shells): New Leaf outputs the material's constant colour and
    # constant alpha (~0.3), so draw them unlit, untextured and translucent after the solid parts.
    for mi, m in glow:
        k = m['colors']['constant0']
        vname = f'pc_nlhat_{name}_{mi}_v'; vs = m['vertices']
        out.append(f'static Vtx {vname}[] ATTRIBUTE_ALIGN(32) = {{')
        for v in vs:
            x, y, z = (int(round(c*K)) for c in v['position'])
            out.append('{{{%d,%d,%d},0,{0,0},{255,255,255,255}}},' % (x, y, z))
        out.append('};')
        dl += ['gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_OFF),',
               f"gsDPSetPrimColor(0,128,{k['R']},{k['G']},{k['B']},{k['A']}),",
               'gsDPSetCombineLERP(0,0,0,PRIMITIVE,0,0,0,PRIMITIVE,0,0,0,COMBINED,0,0,0,COMBINED),',
               'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_XLU_SURF2),',
               'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_CULL_BACK|G_FOG|G_SHADING_SMOOTH),']
        for base in range(0, len(vs), 30):
            kk = min(30, len(vs)-base); dl.append(f'gsSPVertex(&{vname}[{base}],{kk},0),')
            dl += [f'gsSP1Triangle({j},{j+1},{j+2},0),' for j in range(0, kk, 3)]
        dl += ['gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),', 'gsDPSetPrimColor(0,128,255,255,255,255),']
        used += 1
    dl += ['gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_OPA_SURF2),', 'gsSPEndDisplayList(),', '};']
    return (out+dl) if used else None

def main():
    names = sorted(p.name for p in SRC.iterdir() if p.is_dir() and (p/f'{p.name}.json').exists())
    for old in OUTDIR.glob('pc_nl_hats_*.c'): old.unlink()
    chunks = [[]]; size = 0; kept = []
    for n in names:
        code = hat(n)
        if code is None: continue
        sz = sum(len(l) for l in code)
        if size and size+sz > CHUNK: chunks.append([]); size = 0
        chunks[-1].append(code); size += sz; kept.append(n)
    for k, ch in enumerate(chunks):
        (OUTDIR/f'pc_nl_hats_{k}.c').write_text('\n'.join(HEAD+[l for c in ch for l in c])+'\n')
    tab = HEAD+[f'extern Gfx pc_nlhat_{n}[];' for n in kept]
    tab += [f'int pc_nl_hat_count = {len(kept)};', 'Gfx* pc_nl_hat_dl[] = {']+[f'    pc_nlhat_{n},' for n in kept]+['};',
            'const char* pc_nl_hat_name[] = {']+[f'    "{n[4:]}",' for n in kept]+['};']
    # hair ornaments sit on the full hairstyle; real hats go over the short (b) one
    orn = ('cap_feather_', 'cap_hair_', 'cap_hairpin_', 'cap_crown_queen', 'cap_halo', 'cap_glow_')
    tab += ['const short pc_nl_hat_minx[] = {'+', '.join(str(MINX[n]) for n in kept)+'};']
    tab += ['const unsigned char pc_nl_hat_fullhair[] = {', '    '+', '.join('1' if n.startswith(orn) else '0' for n in kept), '};']
    (OUTDIR/'pc_nl_hats.c').write_text('\n'.join(tab)+'\n')
    cm = OUTDIR.parent/'CMakeLists.txt'; t = cm.read_text()
    t = re.sub(r'\n    \$\{CMAKE_CURRENT_SOURCE_DIR\}/src/pc_nl_hats(_\d+)?\.c', '', t)
    t = t.replace('    ${CMAKE_CURRENT_SOURCE_DIR}/src/pc_nl_heads.c\n', '    ${CMAKE_CURRENT_SOURCE_DIR}/src/pc_nl_heads.c\n'
                  '    ${CMAKE_CURRENT_SOURCE_DIR}/src/pc_nl_hats.c\n' +
                  ''.join(f'    ${{CMAKE_CURRENT_SOURCE_DIR}}/src/pc_nl_hats_{k}.c\n' for k in range(len(chunks))))
    cm.write_text(t)
    print(len(kept), 'hats in', len(chunks), 'files')

if __name__ == '__main__':
    main()
