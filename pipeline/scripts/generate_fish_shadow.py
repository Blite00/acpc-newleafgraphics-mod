"""New Leaf fish shadow (sdw_fish: a 3D fish silhouette with a separate tail bone) in place of the GC fish shadow
card. Drawn flat on the water surface in the GC shadow's own frame (head at local -z, width scaled by the native
0.4 x-scale), with the tail swinging across 20 frames that follow the GC shadow's 20-step swim cycle. Colour and
fade use the native prim colour/alpha, so size classes, fading and visibility stay native.
Output: pc_fish_shadow.c_inc -> pc_fish_shadow_dl(t).
"""
import json, math
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parent
vs = json.load(open(ROOT/'fish_source/sdw_fish/sdw_fish.json'))['meshes'][0]['vertices']
P = np.array([v['position'] for v in vs]); N = np.array([v['normal'] for v in vs])
bone = np.array([v['nodes'][0] if v['nodes'] else 1 for v in vs])
SZ = 1800.0/(P[:, 2].max()-P[:, 2].min())          # length: the GC card's fish spans ~0.9 of its 2000 units
SX = 1300.0/(P[:, 0].max()-P[:, 0].min())          # width (before the native 0.4 x-scale)
z0 = P[:, 2].max()                                    # NL head end
PIVOT = -15.0                                         # tail bone root
tris = [i for i in range(0, len(vs), 3) if N[i:i+3, 1].mean() > 0]   # top surface only: no double darkening
out = ['/* Generated by generate_fish_shadow.py: New Leaf fish shadow silhouette. */', 'int g_pc_fish_shadow = 1;']
FR = 20
for t in range(FR):
    ang = math.radians(22.0)*math.sin(2*math.pi*t/FR)
    c, s = math.cos(ang), math.sin(ang)
    out.append(f'static Vtx pc_fsdw_{t}_v[] ATTRIBUTE_ALIGN(32) = {{')
    for i in tris:
        for k in range(3):
            x, y, z = P[i+k]
            if bone[i+k] == 2:
                dz = z-PIVOT; x, z = x*c+dz*s, -x*s+dz*c+PIVOT
            gx = x*SX; gz = -1000.0+(z0-z)*SZ
            out.append('{{{%d,0,%d},0,{0,0},{255,255,255,255}}},' % (round(gx), round(gz)))
    out.append('};')
    dl = [f'static Gfx pc_fsdw_{t}[] = {{', 'gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_OFF),',
          'gsDPSetCombineLERP(0,0,0,PRIMITIVE,0,0,0,PRIMITIVE,0,0,0,COMBINED,0,0,0,COMBINED),',
          'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_ZB_XLU_SURF2),', 'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_FOG),']
    n = len(tris)*3
    for base in range(0, n, 30):
        k = min(30, n-base); dl.append(f'gsSPVertex(&pc_fsdw_{t}_v[{base}],{k},0),')
        dl += [f'gsSP1Triangle({j},{j+1},{j+2},0),' for j in range(0, k, 3)]
    out += dl+['gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),', 'gsSPEndDisplayList(),', '};']
out += ['Gfx* pc_fish_shadow_dl(int t) {', f'    static Gfx* f[{FR}] = {{{",".join(f"pc_fsdw_{t}" for t in range(FR))}}};',
        '    extern char* getenv(const char*);', '    if (!g_pc_fish_shadow || getenv("PC_HOUSE_NATIVE") != NULL) return NULL;',
        f'    if (t < 0) t = 0; if (t >= {FR}) t = {FR-1};', '    return f[t];', '}']
(ROOT/'ACGC-PC-Port/pc/src/pc_fish_shadow.c_inc').write_text('\n'.join(out)+'\n')
print('top tris', len(tris), 'scale', round(SX, 1), round(SZ, 1))
