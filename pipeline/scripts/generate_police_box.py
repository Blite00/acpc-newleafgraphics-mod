"""New Leaf police station (sobj_policeA: the grey modern booth, the closest match to the GC police box) in place
of the GC police box. Uniformly scaled to the GC box's height, centred on the GC footprint and turned 45 degrees so
its door faces the same diagonal as the GC door. Summer and winter textures; hardware lit.
Output: pc_police_box.c_inc -> pc_police_box(winter).
"""
import json, math
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent
SRC = ROOT/'police_source/sobj_policeA'
m = json.load(open(SRC/'sobj_policeA/sobj_policeA.json'))['meshes']
mesh = [mm for mm in m if mm['texture'] == 'tex_sobj_police'][0]
vs = mesh['vertices']
P = np.array([v['position'] for v in vs])
S = 5900.0/(47.6*2**0.5)            # turned 45 degrees, its corners stay inside the native 3x3-unit collision block (+-60)
cx = (P[:, 0].min()+P[:, 0].max())/2; cz = (P[:, 2].min()+P[:, 2].max())/2
ang = math.radians(45.0)
c, s_ = math.cos(ang), math.sin(ang)
def rot(x, z): return (x*c+z*s_, -x*s_+z*c)      # +z (door) -> (+x,+z)/sqrt2

def nb(n):
    n = np.array(n, float); n /= max(np.linalg.norm(n), 1e-9)
    x, z = rot(n[0], n[2]); n = np.array([x, n[1], z])
    n = n*0.75+np.array([0, 0.45, 0]); n /= np.linalg.norm(n)
    return ','.join(str(int(round(v*126)) & 255) for v in n)

tw, th = Image.open(SRC/'Textures/season00/season00/tex_sobj_police.png').size
out = ['/* Generated by generate_police_box.py: New Leaf police station for the GC police box. */', 'int g_pc_police_box = 1;']
out.append('static Vtx pc_police_v[] ATTRIBUTE_ALIGN(32) = {')
for i in range(0, len(vs), 3):
    tri = vs[i:i+3]
    su = 2*math.floor(min(v['uv'][0] for v in tri)/2); sv = 2*math.floor(min(v['uv'][1] for v in tri)/2)
    for v in tri:
        x, y, z = v['position']; rx, rz = rot((x-cx)*S, (z-cz)*S)
        out.append('{{{%d,%d,%d},0,{%d,%d},{%s,255}}},' % (round(rx), round(y*S), round(rz),
                   round((v['uv'][0]-su)*tw*32), round((1-(v['uv'][1]-sv))*th*32), nb(v['normal'])))
out.append('};')
from scipy.ndimage import distance_transform_edt
def bleed(im):
    # the atlas islands sit on pure-black padding, which bled in as black seams along every edge: grow each island
    # into the padding so filtering and mirroring only ever pick up the island's own colour
    a = np.asarray(im.convert('RGB')).astype(float)
    pad = a.max(-1) < 10
    if pad.any() and (~pad).any():
        _, (iy, ix) = distance_transform_edt(pad, return_indices=True)
        a = a[iy, ix]
    return Image.fromarray(a.astype(np.uint8), 'RGB').convert('RGBA')
def rgba8(name, im):
    im = bleed(im); im.putalpha(255); w, h = im.size; data = bytearray()
    for ty in range(0, h, 4):
        for tx in range(0, w, 4):
            tile = [im.getpixel((tx+x, ty+y)) for y in range(4) for x in range(4)]
            data.extend(cc for r, g, b, a in tile for cc in (a, r)); data.extend(cc for r, g, b, a in tile for cc in (g, b))
    out.append(f'static u8 {name}[] ATTRIBUTE_ALIGN(32) = {{'); out.extend(','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32)); out.append('};')
for season, folder in (('s', 'season00'), ('w', 'season09')):
    rgba8(f'pc_police_tex_{season}', Image.open(SRC/f'Textures/{folder}/{folder}/tex_sobj_police.png'))
    dl = [f'static Gfx pc_police_{season}[] = {{', 'gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),', 'gsDPSetPrimColor(0,128,255,255,255,255),',
          'gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,0,0,0,COMBINED),',
          'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_OPA_SURF2),',
          f'gsDPSetTextureImage_Dolphin(G_IM_FMT_RGBA,G_IM_SIZ_32b,{tw},{th},pc_police_tex_{season}),',
          f'gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE,0,0,{"GX_MIRROR" if mesh["mapper"]["wrapU"] == 3 else "GX_REPEAT"},{"GX_MIRROR" if mesh["mapper"]["wrapV"] == 3 else "GX_REPEAT"},0,0),',
          'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_CULL_BACK|G_FOG|G_LIGHTING|G_SHADING_SMOOTH),']
    for base in range(0, len(vs), 30):
        k = min(30, len(vs)-base); dl.append(f'gsSPVertex(&pc_police_v[{base}],{k},0),')
        dl += [f'gsSP1Triangle({j},{j+1},{j+2},0),' for j in range(0, k, 3)]
    out += dl+['gsSPEndDisplayList(),', '};']
# night glow: the doorway interior (dark texels in the original sheet) lit by the GC box's window colour/strength
raw = np.asarray(Image.open(SRC/'Textures/season00/season00/tex_sobj_police.png').convert('RGB')).astype(float)
def texel(u, v):
    u = u % 2.0; u = 2.0-u if u > 1 else u; v = v % 2.0; v = 2.0-v if v > 1 else v
    return raw[min(th-1, int((1-v)*th)), min(tw-1, int(u*tw))]
glow = []
for i in range(0, len(vs), 3):
    tri = vs[i:i+3]
    uc = np.mean([v['uv'][0] for v in tri]); vc = np.mean([v['uv'][1] for v in tri])
    n = np.mean([v['normal'] for v in tri], 0)
    Qt = np.array([v['position'] for v in tri])
    in_recess = Qt[:, 0].min() > -31 and Qt[:, 0].max() < 31 and Qt[:, 1].min() > -1 and Qt[:, 1].max() < 73 and not (Qt[:, 1].min() >= 63.9 and (Qt[:, 0].min() < -18.3 or Qt[:, 0].max() > 18.3 or Qt[:, 2].max() > 17.9)) and Qt[:, 2].min() > 2 and Qt[:, 2].max() < 23
    # the whole doorway interior glows (floor and jambs too): lighting only the dark texels left dark gaps in the light
    inside_door = Qt[:, 0].min() > -18.4 and Qt[:, 0].max() < 18.4 and Qt[:, 1].min() > -1 and Qt[:, 1].max() < 66.2 and Qt[:, 2].min() > 2 and Qt[:, 2].max() < 17.9
    if (texel(uc, vc).max() < 90 and in_recess) or inside_door:
        glow.append(tri)
out.append('static Vtx pc_police_glow_v[] ATTRIBUTE_ALIGN(32) = {')
for tri in glow:
    for v in tri:
        x, y, z = v['position']; nn = np.array(v['normal'], float); nn /= max(np.linalg.norm(nn), 1e-9)
        rx, rz = rot((x-cx)*S, (z-cz)*S)          # exactly the body's own faces (no offset: nothing pokes through)
        out.append('{{{%d,%d,%d},0,{0,0},{255,255,255,255}}},' % (round(rx), round(y*S), round(rz)))
out.append('};')
# interior lit like the GC box's door: colour = the native env colour (black by day, warm light at night)
gdl = ['static Gfx pc_police_glow[] = {', 'gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_OFF),',
       'gsDPSetCombineLERP(0,0,0,ENVIRONMENT,0,0,0,1,0,0,0,COMBINED,0,0,0,COMBINED),',
       'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_OPA_DECAL2),',
       'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_FOG|G_SHADING_SMOOTH|G_DECAL_LEQUAL),']
for base in range(0, len(glow)*3, 30):
    k = min(30, len(glow)*3-base); gdl.append(f'gsSPVertex(&pc_police_glow_v[{base}],{k},0),')
    gdl += [f'gsSP1Triangle({j},{j+1},{j+2},0),' for j in range(0, k, 3)]
out += gdl+['gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),', 'gsSPEndDisplayList(),', '};']
print('glow tris', len(glow))
out += ['Gfx* pc_police_glow_dl(void) { extern char* getenv(const char*); return (g_pc_police_box && getenv("PC_HOUSE_NATIVE") == NULL) ? pc_police_glow : NULL; }']
out += ['Gfx* pc_police_box(int winter) { extern char* getenv(const char*); return (g_pc_police_box && getenv("PC_HOUSE_NATIVE") == NULL) ? (winter ? pc_police_w : pc_police_s) : NULL; }']
(ROOT/'ACGC-PC-Port/pc/src/pc_police_box.c_inc').write_text('\n'.join(out)+'\n')
print('tris', len(vs)//3, 'scale', round(S, 1), 'wrap', mesh['mapper']['wrapU'], mesh['mapper']['wrapV'])
