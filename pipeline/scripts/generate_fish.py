"""New Leaf 3D fish models for the GameCube fish frames (hooked, held up, released, museum).

GC fish are authored with length along y (head +y), top along +x and a thin z; each species has three frames
(a straight, b and c with the tail bent to either side). The matching New Leaf fish (x width, y up, z length,
head +z) is turned into that frame, scaled to the GC length, and the tail half is swung for frames b and c, so
the native wiggle animation keeps working. Lit by the game's lights.
Output: pc_fish.c_inc -> pc_fish_dl(native).
"""
import json, re
from pathlib import Path
import numpy as np
from PIL import Image
import native_models as nm
from recolor import recolor, needs_recolor
RECOLORED = []

ROOT = Path(__file__).resolve().parent
SRC = ROOT/'fish_source'
MATCH = {'funa': 'funa', 'hera': 'funa', 'koi': 'koi', 'nisiki': 'nishiki', 'namazu': 'namazu', 'bass': 'black',
         'bassm': 'black', 'bassl': 'black', 'gill': 'blue', 'oonamazu': 'namazu', 'raigyo': 'raigyo', 'nigoi': 'nigoi',
         'ugui': 'ugui', 'oikawa': 'oikawa', 'tanago': 'tanago', 'dojyo': 'dojou', 'wakasagi': 'wakasagi', 'ayu': 'ayu',
         'yamame': 'yamame', 'iwana': 'ooiwana', 'niji': 'nijimasu', 'ito': 'itou', 'sake': 'sake', 'kingyo': 'kingyo',
         'pirania': 'pirania', 'aroana': 'arowana', 'unagi': 'unagi', 'donko': 'donko', 'angel': 'angel', 'gupi': 'guppi',
         'demekin': 'demekin', 'zarigani': 'zarigani', 'kaeru': 'kaeru', 'medaka': 'medaka', 'kurage': 'kurage',
         'suzuki': 'suzuki', 'tai': 'tai', 'isidai': 'ishidai', 'piraluku': 'piraruku'}
TABLE = (ROOT/'ACGC-PC-Port/src/actor/ac_gyoei_model.c_inc').read_text()
gc_names = re.findall(r'extern Gfx (act_f\d+_([a-z0-9]+)_aT_model)\[\];', TABLE)

out = ['/* Generated by generate_fish.py: New Leaf 3D fish fitted to the GC fish frames. */', 'int g_pc_fish = 1;']
swaps = []
def rgba8(name, im):
    im = im.convert('RGBA'); w, h = im.size; data = bytearray()
    for ty in range(0, h, 4):
        for tx in range(0, w, 4):
            tile = [im.getpixel((tx+x, ty+y)) for y in range(4) for x in range(4)]
            data.extend(c for r, g, b, a in tile for c in (a, r)); data.extend(c for r, g, b, a in tile for c in (g, b))
    out.append(f'static u8 {name}[] ATTRIBUTE_ALIGN(32) = {{'); out.extend(','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32)); out.append('};')
def nb(n):
    n = np.array(n, float); n /= max(np.linalg.norm(n), 1e-9)
    return ','.join(str(int(round(c*126)) & 255) for c in n)
# NL (x, y, z) -> GC (x = NL y, y = NL z, z = NL x): a proper rotation
M = np.array([[0, 1, 0], [0, 0, 1], [1, 0, 0]], float)
done = set()
for a_name, sp in gc_names:
    if sp in done or sp not in MATCH: continue
    done.add(sp)
    nl = MATCH[sp]; js = SRC/f'fsh_{nl}/fsh_{nl}.json'
    if not js.exists(): print('missing', nl); continue
    stem = a_name[:-len('_aT_model')]
    f = ROOT/f'ACGC-PC-Port/src/data/model/{stem}.c'
    d = nm.parse_model_file(f)
    meshes = json.load(open(js))['meshes']
    seen = []; vs = []
    for mm in meshes:
        key = (len(mm['vertices']), round(sum(v['position'][0] for v in mm['vertices']), 2))
        if key in seen: continue
        seen.append(key); vs += mm['vertices']
    P = np.array([v['position'] for v in vs], float)
    tpath = SRC/f'fsh_{nl}/{meshes[0]["texture"]}.png'
    if not tpath.exists(): tpath = sorted((SRC/f'fsh_{nl}').glob('*.png'))[0]
    tex = Image.open(tpath).convert('RGBA'); tw, th = tex.size
    # colour-match to the GameCube fish when they clearly differ
    _src = f.read_text()
    _ti = re.search(r'SetTextureImage_Dolphin\(G_IM_FMT_CI, G_IM_SIZ_4b, (\d+), (\d+), (\w+)\)', _src)
    _pl = re.search(r'LoadTLUT_Dolphin\(15, 16, 1, (\w+)\)', _src)
    if _ti and _pl:
        try:
            _gt = np.asarray(nm.decode_ci(nm.blob_first(_ti[3]), int(_ti[1]), int(_ti[2]), nm.palette_first(_pl[1]), 4).convert('RGBA'))
            _na = np.asarray(tex)
            if needs_recolor(_na, _gt, 14.0) and sp not in ("hera",):
                tex = Image.fromarray(recolor(_na, _gt), 'RGBA'); RECOLORED.append(sp)
        except Exception as e: print('no gc tex', sp, e)
    rgba8(f'pc_fish_{sp}_tex', tex)
    for frame in 'abc':
        native = f'{stem}_{frame}T_model'
        gt = d.get(native)
        if not gt: continue
        G = np.array([v[:3] for t in gt for v in t[5]], float)
        ga = np.array([v[:3] for t in d[f'{stem}_aT_model'] for v in t[5]], float)
        glen = ga[:, 1].max()-ga[:, 1].min(); nlen = P[:, 2].max()-P[:, 2].min()
        sc = glen/max(nlen, 1e-6)
        nc = (P.max(0)+P.min(0))/2
        gc_c = (ga.max(0)+ga.min(0))/2
        # tail swing for b / c: GC z of the bent frame tells the side
        swing = 0.0
        if frame != 'a':
            zb = G[:, 2]; side = -1.0 if abs(zb.min()) > abs(zb.max()) else 1.0
            swing = np.radians(28.0)*side
        name = f'pc_fish_{sp}_{frame}'
        out.append(f'static Vtx {name}_v[] ATTRIBUTE_ALIGN(32) = {{')
        for i in range(0, len(vs), 3):
            tri = vs[i:i+3]
            su = 2*np.floor(min(v['uv'][0] for v in tri)/2); sv = 2*np.floor(min(v['uv'][1] for v in tri)/2)
            for v in tri:
                p = np.array(v['position'], float)-nc; n = np.array(v['normal'], float)
                if swing and p[2] < 0:   # tail half bends about the NL up axis, more toward the tip
                    k = min(1.0, -p[2]/max(-P[:, 2].min()+nc[2], 1e-6)); a = swing*k
                    c, s_ = np.cos(a), np.sin(a)
                    p = np.array([p[0]*c+p[2]*s_, p[1], -p[0]*s_+p[2]*c]); n = np.array([n[0]*c+n[2]*s_, n[1], -n[0]*s_+n[2]*c])
                q = M @ (p*sc)+gc_c; nn = M @ n
                out.append('{{{%d,%d,%d},0,{%d,%d},{%s,255}}},' % (round(q[0]), round(q[1]), round(q[2]),
                           round((v['uv'][0]-su)*tw*32), round((1-(v['uv'][1]-sv))*th*32), nb(nn)))
        out.append('};')
        dl = [f'extern Gfx {native}[];', f'static Gfx {name}[] = {{', 'gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),', 'gsDPSetPrimColor(0,128,255,255,255,255),',
              'gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,0,0,0,COMBINED),',
              'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_TEX_EDGE2),',
              f'gsDPSetTextureImage_Dolphin(G_IM_FMT_RGBA,G_IM_SIZ_32b,{tw},{th},pc_fish_{sp}_tex),',
              'gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE,0,0,GX_MIRROR,GX_MIRROR,0,0),',
              'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_FOG|G_LIGHTING|G_SHADING_SMOOTH),']
        for base in range(0, len(vs), 30):
            k = min(30, len(vs)-base); dl.append(f'gsSPVertex(&{name}_v[{base}],{k},0),')
            dl += [f'gsSP1Triangle({j},{j+1},{j+2},0),' for j in range(0, k, 3)]
        out += dl+['gsSPEndDisplayList(),', '};']
        swaps.append((native, name))
a_frames = [(a, b) for a, b in swaps if a.endswith('_aT_model')]
out += ['/* preview gallery: row 0 New Leaf, row 1 native, species idx */', 'Gfx* pc_fish_gallery_dl(int idx, int row) {',
        f'    static Gfx* nat[] = {{{",".join(a for a, _ in a_frames)}}};', f'    static Gfx* nl[] = {{{",".join(b for _, b in a_frames)}}};',
        f'    if (idx < 0 || idx >= {len(a_frames)}) return NULL;', '    return row == 0 ? nl[idx] : nat[idx];', '}']
out += ['Gfx* pc_fish_dl(Gfx* native) {', '    if (!g_pc_fish || native == NULL) return NULL;']
out += [f'    if (native == {a}) return {b};' for a, b in swaps] + ['    return NULL;', '}']
(ROOT/'ACGC-PC-Port/pc/src/pc_fish.c_inc').write_text('\n'.join(out)+'\n')
print('species', len(done), 'frames', len(swaps), 'recoloured', RECOLORED)
