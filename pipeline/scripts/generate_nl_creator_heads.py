"""New Leaf heads for the intro character creator: every New Leaf hairstyle (16 per gender, full 'a' and the short
'b' worn under hats) with its hair colour applied at run time.

Same fitting, smoothing and lighting as generate_nl_heads.py (imported from it), but the hair texture is stored as
colour-free maps so pc_nl_creator.c can paint any hair colour into a texture buffer:
  G = hair brightness (New Leaf grey hair x painted shading x outline), 0..255 = 0..GSCALE
  S = skin weight x outline (the baked New Leaf skin tone, under the run-time skin colour), 0..255
  A = texture alpha (1 = hair/outline, 0 = run-time skin colour)
  texel RGB = colour * G + NL_SKIN * S

Output: pc/src/pc_nl_creator_heads.h (table) + pc/src/pc_nl_creator_heads_N.c (geometry, a few heads per file).
"""
import json, re
from pathlib import Path
import numpy as np
from PIL import Image
import generate_nl_heads as nh

ROOT = Path(__file__).resolve().parent
SRCDIR = ROOT/'ACGC-PC-Port/pc/src'
CMAKE = ROOT/'ACGC-PC-Port/pc/CMakeLists.txt'
STYLES = 16
GSCALE = 1.6
REF = 120
TEX = 64*nh.UP


def hair_maps(n, vs):
    """colour-free maps from the heads thread's own bake (linear in the hair colour): tex(c) = c*G + skin part"""
    t0 = np.asarray(nh.bake_head(n, (0, 0, 0), vs)).astype(float)
    t1 = np.asarray(nh.bake_head(n, (REF, REF, REF), vs)).astype(float)
    G = (t1[..., :3]-t0[..., :3]).mean(-1)/REF
    S = t0[..., :3].mean(-1)/nh.NL_SKIN.mean()
    q = lambda x, k=1.0: np.clip(np.round(x/k*255), 0, 255).astype(np.uint8)
    return q(G, GSCALE), q(S), t0[..., 3].astype(np.uint8)


def tile_order(*planes):
    """the three maps reordered into RGBA8 tile order (4x4 tiles, row-major) so the run-time paint is one pass"""
    out = []
    for p in planes:
        t = p.reshape(TEX//4, 4, TEX//4, 4).transpose(0, 2, 1, 3).reshape(-1)
        out.append(t)
    return np.stack(out, 1).reshape(-1)


def tri_dl(out, name, vname, n):
    dl = [f'Gfx {name}[] = {{']
    nh.tris(dl, vname, n)
    out += dl+['gsSPEndDisplayList(),', '};']


def main():
    blocks = []; table = []
    for sex, sexi, mfile, dlname, skel in nh.PLAYERS:
        s, off = nh.gc_head_fit(mfile, dlname)
        for st in range(STYLES):
            for var in 'ab':
                hs = f'{sex}{st:02d}{var}'
                d = json.load(open(nh.SRC/f'head_mdl/{hs}/{hs}.json'))
                meshes = {m['texture'][0]: m for m in d['meshes']}
                tag = f'pc_cch_{sex}{st:02d}{var}'
                o = []
                G, S, A = hair_maps(hs, meshes['h']['vertices'])
                data = tile_order(G, S, A)
                o.append(f'const u8 {tag}_map[{len(data)}] = {{')
                o += [','.join(map(str, data[i:i+48]))+',' for i in range(0, len(data), 48)]
                o.append('};')
                hv0, ev0, mv0 = meshes['h']['vertices'], meshes['e']['vertices'], meshes['m']['vertices']
                allv = nh.smooth_head(hv0+ev0+mv0)
                k1, k2 = len(hv0)*16, (len(hv0)+len(ev0))*16
                hverts, everts, mverts = allv[:k1], allv[k1:k2], allv[k2:]
                tw = th = TEX
                def uv_head(u, tri):
                    su = sv = 0
                    if nh.uv_wraps(meshes['h']['vertices']) and not all(0 <= x <= 1 for v in tri for x in v['uv']):
                        su = 2*np.floor(min(v['uv'][0] for v in tri)/2); sv = 2*np.floor(min(v['uv'][1] for v in tri)/2)
                        if max(abs(tri[0]['uv'][k]-tri[j]['uv'][k]) for j in (1,2) for k in (0,1)) < 0.02 and abs(np.mean([v['position'][1] for v in tri])) < 9 and ((np.mean([v['position'][0] for v in tri]) < 10.5 and np.mean([v['position'][2] for v in tri]) > 4.8) or (np.mean([v['position'][0] for v in tri]) < 5.5 and np.mean([v['position'][2] for v in tri]) > 2.5)):   # lower-front single-texel triangle: wrap by whole tiles, don't clamp to the edge
                            su = np.floor(tri[0]['uv'][0]); sv = np.floor(tri[0]['uv'][1])
                    return (u[0]-su)*tw*32, (1-(u[1]-sv))*th*32
                nh.emit_vtx(o, f'{tag}_hv', hverts, s, off, uv_head)
                nh.emit_vtx(o, f'{tag}_ev', everts, s, off, lambda u, tri: (u[0]*32*32, (1-u[1])*16*32))
                nh.emit_vtx(o, f'{tag}_mv', mverts, s, off, lambda u, tri: (u[0]/2*32*32, (1-u[1])*16*32))
                tri_dl(o, f'{tag}_h', f'{tag}_hv', len(hverts))
                tri_dl(o, f'{tag}_e', f'{tag}_ev', len(everts))
                tri_dl(o, f'{tag}_m', f'{tag}_mv', len(mverts))
                blocks.append(o)
                table.append((sexi, st, var, tag))
                print(hs, len(hverts)//3, 'tris', round(s, 1))
    hdr = ['/* Generated by generate_nl_creator_heads.py: New Leaf hairstyles for the character creator. */',
           '#include "pc_platform.h"', '#include "PR/mbi.h"', '#include "libultra/libultra.h"',
           '#include "libforest/gbi_extensions.h"', '']
    for old in SRCDIR.glob('pc_nl_creator_heads_*.c'): old.unlink()
    per = 4; files = []
    for k in range(0, len(blocks), per):
        f = SRCDIR/f'pc_nl_creator_heads_{k//per}.c'; files.append(f.name)
        f.write_text('\n'.join(hdr+[l for b in blocks[k:k+per] for l in b])+'\n')
    h = ['/* Generated by generate_nl_creator_heads.py */', '#ifndef PC_NL_CREATOR_HEADS_H', '#define PC_NL_CREATOR_HEADS_H',
         f'#define PC_CCH_STYLES {STYLES}', f'#define PC_CCH_TEX {TEX}', f'#define PC_CCH_GSCALE {GSCALE}f',
         f'#define PC_CCH_SKIN_R {int(nh.NL_SKIN[0])}', f'#define PC_CCH_SKIN_G {int(nh.NL_SKIN[1])}', f'#define PC_CCH_SKIN_B {int(nh.NL_SKIN[2])}']
    for sexi, st, var, tag in table:
        h += [f'extern const u8 {tag}_map[];', f'extern Gfx {tag}_h[];', f'extern Gfx {tag}_e[];', f'extern Gfx {tag}_m[];']
    h.append('typedef struct { const u8* map; Gfx* h; Gfx* e; Gfx* m; } PcCchHead;')
    h.append(f'static const PcCchHead pc_cch_heads[2][{STYLES}][2] = {{')
    for sexi in (0, 1):
        h.append('  {')
        for st in range(STYLES):
            ent = []
            for var in 'ab':
                tag = next(t for s_, s2, v, t in table if s_ == sexi and s2 == st and v == var)
                ent.append(f'{{ {tag}_map, {tag}_h, {tag}_e, {tag}_m }}')
            h.append('    { '+', '.join(ent)+' },')
        h.append('  },')
    h += ['};', '#endif']
    (SRCDIR/'pc_nl_creator_heads.h').write_text('\n'.join(h)+'\n')
    t = CMAKE.read_text()
    t = re.sub(r'\n    \$\{CMAKE_CURRENT_SOURCE_DIR\}/src/pc_nl_creator[\w]*\.c', '', t)
    anchor = '    ${CMAKE_CURRENT_SOURCE_DIR}/src/pc_nl_heads.c\n'
    add = '    ${CMAKE_CURRENT_SOURCE_DIR}/src/pc_nl_creator.c\n'+''.join(f'    ${{CMAKE_CURRENT_SOURCE_DIR}}/src/{n}\n' for n in files)
    assert anchor in t
    t = t.replace(anchor, add+anchor)
    CMAKE.write_text(t)
    print('files', files)


if __name__ == '__main__':
    main()
