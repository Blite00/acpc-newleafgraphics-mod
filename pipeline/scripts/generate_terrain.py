"""Adapt locally extracted New Leaf surfaces to the original acre UV strips."""
from pathlib import Path
import re,json,struct
import numpy as np
from PIL import Image,ImageDraw,ImageFilter

ROOT=Path(__file__).resolve().parent
SRC=ROOT/'terrain_source'
CODE=ROOT/'ACGC-PC-Port'
rel=(ROOT/'foresta.rel').read_bytes()
assets=(CODE/'pc/src/pc_assets.c').read_text()

def indices(name,w):
    m=re.search(r'\{"assets/'+name+r'\.bin",.*?, (0x[0-9A-F]+), (0x[0-9A-F]+),',assets)
    size,off=map(lambda x:int(x,16),m.groups())
    b=rel[off:off+size]; a=np.zeros((w,w),np.uint8); n=0
    for ty in range(0,w,8):
        for tx in range(0,w,8):
            for y in range(8):
                for x in range(8):
                    a[ty+y,tx+x]=(b[n//2]>>(4 if n%2==0 else 0))&15;n+=1
    return a

def array(name,a):
    b=a.astype(np.uint8).tobytes()
    return 'static const unsigned char '+name+'[] = {\n'+''.join(','.join(map(str,b[i:i+32]))+',\n' for i in range(0,len(b),32))+'};\n'

stone_rgba=np.asarray(Image.open(SRC/'texset_village/tex_smat.png').convert('RGBA'))
stone=stone_rgba[:,:,:3].astype(float)
# Preserve the extracted donor paving RGB without exposure or saturation grading.
stone_normal=np.asarray(Image.open(SRC/'texset_village/tex_flocky_smat.png').convert('RGB'))
# The donor's dirt is shaded from material constant1, not a dirt albedo map.
material=(SRC/'grd_F_0.bcres').read_bytes()
mtob=material.index(b'MTOB')-4
# CGFX also stores float colors; preserve these instead of the exporter's
# rounded RGBA8 copy (constant1 is 0.82, 0.71, 0.50 in the source).
base=np.array(struct.unpack_from('<4f',material,mtob+36+6*16)[:3])*255.0
normal=np.asarray(Image.open(SRC/'grassA_season02/tex_flocky_grd.png').convert('RGB').resize((128,128))).astype(float)
# The source dirt albedo is its material constant. Keep fine relief in the
# actual normal map instead of baking an invented grain pattern into RGB.
dirt=np.broadcast_to(base,(128,128,3)).copy()
out=['/* Generated by generate_terrain.py; original topology and UVs remain native. */\n']
# Verified donor runtime 0x1f52c8 reads 10 x 3 RGB float constants from
# virtual 0x902d04; getter 0x5c1070 clamps and truncates float32*255.
with open(Path(__file__).resolve().parent/'_code.bin','rb') as donor:   # the ROM's ExeFS .code (setup)
    donor.seek(0x902d04-0x100000)
    seasonal_material=np.frombuffer(donor.read(10*9*4),dtype='<f4').reshape(10,3,3)
material_bytes=np.clip(seasonal_material*np.float32(255),0,255).astype(np.uint8)
out.append('static const unsigned char pc_terrain_material_colors[10][3][3] = {\n')
for row in material_bytes:
    out.append('{'+','.join('{'+','.join(map(str,color))+'}' for color in row)+'},\n')
out.append('};\n')
checks=[]
sheet=Image.new('RGB',(768,420),'#ddd');draw=ImageDraw.Draw(sheet)
for style,letter in enumerate('ACB'): # native: triangle, square, circle
    suffix='' if style==0 else '_'+str(style+1)
    grass_rgba=np.asarray(Image.open(SRC/f'grass{letter}_season02/tex_grass.png').convert('RGBA'))
    grass=grass_rgba[:,:,:3]
    lawn=np.tile(grass,(2,2,1)).astype(float)
    for kind,w in [('grass',32),('earth',64),('stone',64)]:
        if kind=='grass': rgb=grass
        else:
            idx=indices('mFM_grd_s_'+kind+suffix+'_tex',64)
            # Native U stores the old star-shaped blades; V follows distance into
            # the path. Recover its area coverage per row instead of carrying
            # the old blade silhouette into the donor material. A constant-U
            # field wraps exactly; top/bottom retain native grass/path endpoints.
            profile=(idx<4).mean(axis=1)
            profile=np.minimum.accumulate(profile)
            broad=np.broadcast_to(profile[:,None],(64,64))
            mask=Image.fromarray(np.rint(broad*255).astype(np.uint8)).resize((128,128),Image.Resampling.BILINEAR)
            assert np.array_equal(np.asarray(mask)[:,0],np.asarray(mask)[:,-1])
            alpha=np.asarray(mask).astype(float)[:,:,None]/255
            surface=dirt if kind=='earth' else stone
            rgb=np.rint(lawn*alpha+surface*(1-alpha)).astype(np.uint8)
            # Every pure grass pixel must be exactly the corresponding lawn sample.
            assert np.array_equal(rgb[alpha[:,:,0]==1],lawn.astype(np.uint8)[alpha[:,:,0]==1])
            checks.append(dict(style=letter,kind=kind,grass_phase_exact=True))
        rgba=np.dstack([rgb,np.full(rgb.shape[:2],255,np.uint8)])
        Image.fromarray(rgba).save(SRC/f'adapted_{letter}_{kind}.png')
        # Separate the native edge mask from planar surface coordinates. Acre UV
        # strips turn and mirror; using those UVs for paving cuts stones in half.
        edge=np.full((128,128),255,np.uint8) if kind=='grass' else np.asarray(mask)
        packed=np.zeros((128,1024,4),np.uint8); packed[:,:,3]=255
        packed[:,:128,:3]=edge[:,:,None]
        packed[:,128:256,:3]=lawn.astype(np.uint8)
        # Ground TEV uses texture1 alpha for the wear/tint transition.
        packed[:,128:256,3]=np.tile(grass_rgba[:,:,3],(2,2))
        packed[:,256:384,:3]=dirt.astype(np.uint8)
        packed[:,384:512,:3]=stone.astype(np.uint8)
        # m_smat uses its texture alpha to gate specular in TEV stage 1.
        packed[:,384:512,3]=stone_rgba[:,:,3]
        packed[:,512:640,:3]=normal.astype(np.uint8)
        packed[:,640:768,:3]=stone_normal
        out.append(array(f'pc_terrain_{style}_{kind}',packed))
        if style==0:
            x={'grass':0,'earth':256,'stone':512}[kind]
            sheet.paste(Image.fromarray(rgba).resize((256,256),Image.Resampling.NEAREST),(x,35))
            draw.text((x+8,12),kind,fill='black')
# Shared seasonal cells keep the nine native boundary atlases small. Runtime
# copies only the grass and ground-normal cells for the selected calendar set.
for style,letter in enumerate('ACB'):
    for season in range(10):
        grass_season=np.asarray(Image.open(SRC/f'grass{letter}_season{season:02}/tex_grass.png').convert('RGBA'))
        out.append(array(f'pc_terrain_grass_{style}_{season}',np.tile(grass_season,(2,2,1))))
for season in range(10):
    normal_season=np.asarray(Image.open(SRC/f'grassA_season{season:02}/tex_flocky_grd.png').convert('RGBA').resize((128,128)))
    out.append(array(f'pc_terrain_normal_{season}',normal_season))
out.append('static const unsigned char* pc_terrain_grass_seasons[3][10] = {\n')
for style in range(3):out.append('{'+','.join(f'pc_terrain_grass_{style}_{season}' for season in range(10))+'},\n')
out.append('};\nstatic const unsigned char* pc_terrain_normal_seasons[10] = {'+','.join(f'pc_terrain_normal_{season}' for season in range(10))+'};\n')
out.append('static const unsigned char* pc_terrain_pixels[3][3] = {\n')
for i in range(3):out.append('{'+','.join(f'pc_terrain_{i}_{k}' for k in ['grass','earth','stone'])+'},\n')
out.append('};\n')
(CODE/'pc/src/pc_terrain_data.c_inc').write_text(''.join(out))
(SRC/'seam_checks.json').write_text(json.dumps(checks,indent=2))
draw.text((8,315),'3DS surfaces fitted to the original grass / path / paving boundaries.',fill='black')
draw.text((8,340),'Dirt: exact donor material color; relief comes from its normal map.',fill='black')
sheet.save(SRC/'adapted_terrain.png')
print('Generated nine terrain textures; six grass-phase checks passed.')
