"""GameCube house gyroid, upscaled: smoother PN-tessellated geometry and seam-safe 4x Real-ESRGAN textures.

Same skeleton, joints and animation as the GC gyroid; each joint's display list is rebuilt. The head's neck
seam is skinned to the body joint (two matrices), so those triangles are kept as they are and only re-textured;
everything else is tessellated (level 3) along the original vertex normals and keeps hardware lighting.
"""
import re, shutil, subprocess
from pathlib import Path
import numpy as np
from PIL import Image
import native_models as nm

ROOT = Path(__file__).resolve().parent
src = (ROOT/'generate_mailbox_hd.py').read_text()
exec(src[src.index('def _pad_mode'):src.index('# ---------------- textures')])   # upscale_all (wrap-aware)
exec(src[src.index('GEO_NORMALS = {}'):src.index('def native_tris')])                    # pn_tess
W = ROOT/'gyroid_hd'; UP = 8; PAD = 8; DETAIL = 1.0; PN_STRENGTH = 0.3   # light rounding only: keep the hat brim and edges crisp
ESR = ROOT/'toolchain/realesrgan/realesrgan-ncnn-vulkan.exe'
MODEL = ROOT/'ACGC-PC-Port/src/data/model/hnw_model.c'
LEVEL = 3

text = MODEL.read_text()
TMEM = nm.blob('hnw_tmem_txt'); PAL = nm.palette('hnw_face'); VERTS = nm.vertices('hnw_v')

def parse(name):
    body = re.search(rf'Gfx {name}\[\] = \{{(.*?)\n\}};', text, re.S)[1]
    tex = None; slot = {}; tris = []; batch = 0; pend = 0; mode = None
    for op, args in re.findall(r'(gs\w+)\(([^)]*)\)', body):
        a = [x.strip() for x in args.split(',')]
        if op == 'gsSPMatrix': batch += 1
        elif op == 'gsDPSetTextureImage_Dolphin':
            off = int(a[4].split('+')[1], 16) if '+' in a[4] else 0
            tex = (off, int(a[2]), int(a[3]))
        elif op == 'gsDPSetTile_Dolphin': mode = (a[3], a[4])
        elif op == 'gsSPVertex':
            m = re.match(r'&?hnw_v(?:\[(\d+)\])?', a[0]); st = int(m[1] or 0)
            for k in range(int(a[1])): slot[int(a[2])+k] = (st+k, batch)
        elif op in ('gsSPNTrianglesInit_5b', 'gsSPNTriangles_5b'):
            if op == 'gsSPNTrianglesInit_5b': pend = int(a[0]); idx = list(map(int, a[1:10]))
            else: idx = list(map(int, a[:12]))
            for k in range(0, len(idx), 3):
                if pend > 0:
                    tris.append(dict(tex=tex, mode=mode or ('GX_CLAMP', 'GX_CLAMP'), slots=idx[k:k+3], src=[slot[i] for i in idx[k:k+3]])); pend -= 1
    return tris

PARTS = ['head_hnw_model', 'body_hnw_model', 'handL_hnw_model', 'handR_hnw_model']
parsed = {p: parse(p) for p in PARTS}
textures = {}
for tris in parsed.values():
    for t in tris: textures[t['tex']] = t['mode']
jobs = []
for (off, w, h), (mu, mv) in textures.items():
    im = nm.decode_ci(TMEM[off:off+w*h//2], w, h, PAL, 4)
    jobs.append((f't{off:04x}', im, mu, mv))
up = upscale_all(jobs)

out = ['/* Generated by generate_gyroid_hd.py: GC house gyroid, PN-tessellated with upscaled textures. */', 'int g_pc_gyroid_hd = 1;']
declared = set()
def tex_array(name, im):
    if name in declared: return
    declared.add(name); data = bytearray(); w, h = im.size
    for ty in range(0, h, 4):
        for tx in range(0, w, 4):
            tile = [im.getpixel((tx+x, ty+y)) for y in range(4) for x in range(4)]
            data.extend(c for r, g, b, a in tile for c in (a, r)); data.extend(c for r, g, b, a in tile for c in (g, b))
    out.append(f'static u8 {name}[] ATTRIBUTE_ALIGN(32) = {{'); out.extend(','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32)); out.append('};')
for (off, w, h) in textures: tex_array(f'pc_hnw_t{off:04x}', up[f't{off:04x}'])

def set_tex(t):
    off, w, h = t['tex']; mu, mv = t['mode']
    return [f'gsDPSetTextureImage_Dolphin(G_IM_FMT_RGBA,G_IM_SIZ_32b,{w*UP},{h*UP},pc_hnw_t{off:04x}),',
            f'gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE,0,0,{mu},{mv},0,0),']

def vdata(i):
    x, y, z, _f, s, t, r, g, b, a = VERTS[i]
    return ((x, y, z), (s/32.0, t/32.0), [c-256 if c > 127 else c for c in (r, g, b)])

PRE = ['gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),', 'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_OPA_SURF2),',
       'gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,0,0,0,COMBINED),', 'gsDPSetPrimColor(0,128,255,255,255,255),']
counts = {}
for part in PARTS:
    tris = parsed[part]; dl = []
    skinned = part == 'head_hnw_model'
    seam = [t for t in tris if skinned and any(s[0] < 30 for s in t['src'])]
    rest = [t for t in tris if t not in seam]
    if seam:
        # neck seam: two matrices exactly like the native list, re-textured only
        dl += ['gsSPMatrix(anime_6_mdl,G_MTX_NOPUSH|G_MTX_LOAD|G_MTX_MODELVIEW),', 'gsSPVertex(pc_hnw_seam_v,12,0),',
               'gsSPMatrix(&anime_6_mdl[1],G_MTX_NOPUSH|G_MTX_LOAD|G_MTX_MODELVIEW),', 'gsSPVertex(&pc_hnw_seam_v[12],18,12),'] + PRE
        out.append('static Vtx pc_hnw_seam_v[] ATTRIBUTE_ALIGN(32) = {')
        for i in range(30):
            x, y, z, f, s, t, r, g, b, a = VERTS[i]
            out.append('{{{%d,%d,%d},%d,{%d,%d},{%d,%d,%d,%d}}},' % (x, y, z, f, s*UP, t*UP, r, g, b, a))
        out.append('};')
        cur = None
        for t in seam:
            if t['tex'] != cur: dl += set_tex(t); cur = t['tex']
            dl.append('gsSP1Triangle(%d,%d,%d,0),' % tuple(t['slots']))
    else:
        dl += PRE
    set_geo_normals([[vdata(s[0]) for s in t['src']] for t in tris])
    PINNED.clear(); PINNED.update(pkey(vdata(s[0])[0]) for t in seam for s in t['src'])
    groups = {}
    for t in rest: groups.setdefault(t['tex'], []).extend(pn_tess([vdata(s[0]) for s in t['src']], LEVEL))
    total = len(seam)
    for key, tt in groups.items():
        vname = f'pc_hnw_{part.split("_")[0]}_{key[0]:04x}_v'; verts = [v for tri in tt for v in tri]
        out.append(f'static Vtx {vname}[] ATTRIBUTE_ALIGN(32) = {{')
        for pos, uv, n in verts:
            nb = ','.join(str(int(round(c*126)) & 255) for c in n)
            out.append('{{{%d,%d,%d},0,{%d,%d},{%s,255}}},' % (round(pos[0]), round(pos[1]), round(pos[2]), round(uv[0]*UP*32), round(uv[1]*UP*32), nb))
        out.append('};')
        dl += set_tex({'tex': key, 'mode': textures[key]})
        for base in range(0, len(verts), 30):
            c = min(30, len(verts)-base)
            dl.append(f'gsSPVertex(&{vname}[{base}],{c},0),')
            for k in range(0, c, 3): dl.append(f'gsSP1Triangle({k},{k+1},{k+2},0),')
        total += len(tt)
    out += [f'static Gfx pc_hnw_{part}[] = {{'] + dl + ['gsSPEndDisplayList(),', '};']
    counts[part] = (len(tris), total)
out += ['Gfx* pc_gyroid_hd_joint(int joint) {', '    if (!g_pc_gyroid_hd) return NULL;',
        '    switch (joint) { case 1: return pc_hnw_body_hnw_model; case 2: return pc_hnw_head_hnw_model;',
        '                     case 4: return pc_hnw_handL_hnw_model; case 6: return pc_hnw_handR_hnw_model; }', '    return NULL;', '}']
(ROOT/'ACGC-PC-Port/pc/src/pc_gyroid_hd.c_inc').write_text('\n'.join(out)+'\n')
for (key, im, mu, mv) in jobs: up[key].save(W/f'final_{key}.png') if W.exists() else None
print('triangles native->hd', counts, 'textures', len(textures))
