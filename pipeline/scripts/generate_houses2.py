def gc_tinted_roof(pal, winter):
    # winter = New Leaf's own snowed-over roof (season09: snow blanket with a wavy overhang, shingles peeking
    # out at the edges); only its roof-coloured pixels are recoloured to the GC palette
    src = M/f'Textures/{"season09" if winter else "season00"}/roof_00_raw.png'
    a = np.asarray(Image.open(src).convert('RGBA')).astype(float).copy()
    rgb = a[..., :3]; mx = rgb.max(-1); mn = rgb.min(-1); sat = (mx-mn)/np.maximum(mx, 1)
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    red = (sat > 0.35) & (r > g+25) & (r > b+15) & (g < r*0.75)
    lum = rgb @ np.array([0.3, 0.59, 0.11])
    lo, hi = np.percentile(lum[red], 3), np.percentile(lum[red], 97)
    t = np.clip((hi-lum)/max(hi-lo, 1), 0, 1)*1.15-0.05      # 0 = brightest ramp entry
    ramp = gc_roof_ramp(pal, 0); xs = np.linspace(0, 1, len(ramp))
    tc = np.clip(t, 0, 1)
    col = np.stack([np.interp(tc, xs, ramp[:, c]) for c in range(3)], -1)
    col *= np.clip(1-np.minimum(t, 0)*-1.0, 0.9, 1.1)[..., None]*np.where(t > 1, 1-(t-1)*1.2, 1)[..., None]
    a[..., :3] = np.where(red[..., None], col, rgb)
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), 'RGBA')
def neutral_wall():
    """wall_00 (white plaster, wooden window frames) with its pink tile accents muted to pale stone"""
    a = np.asarray(Image.open(M/'Textures/season00/wall_00_raw.png').convert('RGBA')).astype(float).copy()
    rgb = a[..., :3]; r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    mx = rgb.max(-1); mn = rgb.min(-1); sat = (mx-mn)/np.maximum(mx, 1)
    h = a.shape[0]; rows = np.arange(h)[:, None]*np.ones((1, a.shape[1]))
    wood = (r > g+10) & (g > b+10) & (mx < 200)
    accent = (sat > 0.06) & ~wood & (rows > 0.35*h) & (rows < 0.86*h)
    grey = rgb @ np.array([0.3, 0.59, 0.11])
    stone = np.stack([grey*1.03+8, grey*1.01+6, grey*0.96+2], -1)
    a[..., :3] = np.where(accent[..., None], stone*0.85+rgb*0.15, rgb)
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), 'RGBA')

