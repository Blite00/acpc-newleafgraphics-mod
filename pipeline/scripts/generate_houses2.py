def door_variant(im, lit):
    a = np.asarray(im.convert('RGBA')).astype(float).copy()
    glass = a[..., 3] < 110
    if lit: col = np.array([255, 226, 140.0])
    else: col = np.array([160, 200, 230.0])
    gradient = np.linspace(1.0, 0.8, a.shape[0])[:, None]
    for c in range(3): a[..., c] = np.where(glass, col[c]*gradient, a[..., c])
    a[..., 3] = 255
    return Image.fromarray(a.astype(np.uint8), 'RGBA')

