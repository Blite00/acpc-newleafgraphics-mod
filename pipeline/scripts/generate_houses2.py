def geometry(name, vertices, transform, w, h, flip_v=False):
    out.append(f'static const PC_TreeSourceLight {name}_light[] = {{')
    for v in vertices:
        n = v['normal']; length = sum(c*c for c in n)**.5 or 1
        out.append('{{%s},{%s}},' % (','.join('%.6ff' % (c/length) for c in n), ','.join(str((v['color'] >> b) & 255) for b in (16, 8, 0, 24))))
    out.append('};')
    out.append(f'static Vtx {name}_v[] ATTRIBUTE_ALIGN(32) = {{')
    # texture coords are s16 texels*32: far-out donor UVs (roof eaves reach u=-4.3) overflowed and clamped, which
    # smeared one texel column across the eave. Shift each triangle by a whole even number of tiles (identical
    # under both repeat and mirror wrapping) so its UVs sit near the origin.
    shift = []
    for i in range(0, len(vertices), 3):
        tri = vertices[i:i+3]
        su = 2*np.floor(min(v['uv'][0] for v in tri)/2); sv = 2*np.floor(min(v['uv'][1] for v in tri)/2)
        shift += [(su, sv)]*len(tri)
    for v, (su, sv) in zip(vertices, shift):
        x, y, z = transform(v['position'])
        u, t = v['uv']; u -= su; t -= sv; u = round(u*w*32); t = round((t if flip_v else 1-t)*h*32)
        out.append('{{{%d,%d,%d},1,{%d,%d},{%s}}},' % (round(x), round(y), round(z), max(-32768, min(32767, u)), max(-32768, min(32767, t)),
                   ','.join(str((v['color'] >> s) & 255) for s in (16, 8, 0, 24))))
    out.append('};'); out.append(f'static Gfx {name}_geo[] = {{')
    for base in range(0, len(vertices), 30):
        count = min(30, len(vertices)-base)
        out.append(f'gsSPVertex(&{name}_v[{base}],{count},0),')
        idx = list(range(count)); out.append('gsSPNTrianglesInit_5b(%d,%s),' % (count//3, ','.join(map(str, (idx+[0]*9)[:9]))))
        for i in range(9, count, 12): out.append('gsSPNTriangles_5b(%s),' % ','.join(map(str, (idx[i:i+12]+[0]*12)[:12])))
    out.append('gsSPEndDisplayList(),'); out.append('};')
    lights.append((name, len(vertices)))

def door_geo(S_x, S_y):
    m = json.loads((D/'hobj_door_a/hobj_door_a.json').read_text())['meshes'][0]
    zb = min(v['position'][2] for v in m['vertices'])
    off = 0.0  # hinge stays at the joint origin; the joint itself is moved to the doorway edge in C
    tr = lambda p: ((DOOR_W/2-p[0])*S_x+off, (p[1]+2.0)*S_y, -(p[2]-zb)*S_x)
    return m, tr

