def roof_mean(path):
    im = np.asarray(Image.open(path).convert('RGB')).astype(float)
    return im[:int(im.shape[0]*0.6)].reshape(-1, 3).mean(0)

def gc_roof_color(house, letter, season):
    """mean roof-role colour of the GC house for a palette letter"""
    dls = nm.parse_model_file(ROOT/'ACGC-PC-Port/src/data/model/obj_s_house1.c')
    cols = []; weights = []
    for part in ('t1', 't2', 't3'):
        for t in dls.get(f'obj_{season}_house{house}_{part}_model', []):
            tex = t[0]
            w, h = t[3], t[4]
            img = nm.decode_ci(nm.blob(tex), w, h, nm.palette(f'obj_{season}_house{house}_{letter}_pal'), 4)
            a = np.asarray(img).astype(float)
            uv = np.array([(v[3], v[4]) for v in t[5]]); n = np.cross(np.array(t[5][1][:3])-np.array(t[5][0][:3]), np.array(t[5][2][:3])-np.array(t[5][0][:3]))
            if n[1] <= 0: continue
            cx, cy = int(uv[:, 0].mean()) % w, int(uv[:, 1].mean()) % h
            px = a[cy, cx]
            if px[3] > 100: cols.append(px[:3])
    return np.mean(cols, 0) if cols else np.array([150.0, 60, 50])

