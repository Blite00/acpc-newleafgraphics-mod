"""Original 3DS weeds and flowers for the native weed/flower draw routes.

Weeds A/B/C use the 23 seasonal fg_bush atlases. Flowers use the original
season-independent t_flower atlas; native item IDs choose the species/color.
The donor has no purple or blue cosmos, so those two are original donor
cosmos geometry with petals recolored from the pink/white donor cosmos
(an explicit adaptation; every other color is an original donor model).
Gameplay, picking, growth, collision and shadows remain native.
"""
import colorsys, json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent
SRC = ROOT/'tree_source'
SCALE = 12243/83.0161  # tree scale; keeps the original 3DS plant proportions

def mesh(folder, name):
    return json.loads((SRC/folder/(name+'.json')).read_text())['meshes'][0]

def gx_rgba8(im):
    w, h = im.size; data = bytearray()
    for ty in range(0, h, 4):
        for tx in range(0, w, 4):
            tile = [im.getpixel((tx+x, ty+y)) for y in range(4) for x in range(4)]
            data.extend(c for r, g, b, a in tile for c in (a, r)); data.extend(c for r, g, b, a in tile for c in (g, b))
    return data

out = ['/* Generated by generate_ground_plants.py; original donor geometry, colors and normals. */',
       'int g_pc_ground_plants = 1;']
def array(name, data):
    out.append(f'static u8 {name}[] ATTRIBUTE_ALIGN(32) = {{')
    out.extend(','.join(map(str, data[i:i+32]))+',' for i in range(0, len(data), 32))
    out.append('};')

# Weeds: seasonal fg_bush atlas.
names = []; seen = {}
for season in range(23):
    im = Image.open(SRC/f'season{season:02}_normals/fg_bush.png').convert('RGBA')
    raw = im.tobytes()
    if raw in seen: names.append(seen[raw]); continue
    name = f'pc_weed_season{season:02}_tex'; seen[raw] = name; names.append(name)
    array(name, gx_rgba8(im))
bush_size = im.size
out.append('static u8* pc_weed_atlases[23]={'+','.join(names)+'};')

# Flowers: one original atlas plus the derived purple/blue cosmos atlas.
flower = Image.open(SRC/'season08_normals/t_flower.png').convert('RGBA')
fw, fh = flower.size

def uv_pixels(vertices):
    """Atlas texels covered by a model's triangles (mirrored wrapping)."""
    def wrap(x):
        x = x % 2; return 2-x if x > 1 else x
    pix = set()
    for i in range(0, len(vertices), 3):
        tri = [(v['uv'][0]*fw, (1-v['uv'][1])*fh) for v in vertices[i:i+3]]
        xs = [p[0] for p in tri]; ys = [p[1] for p in tri]
        for py in range(int(min(ys))-1, int(max(ys))+2):
            for px in range(int(min(xs))-1, int(max(xs))+2):
                x, y = px+.5, py+.5
                d = [(tri[(k+1)%3][0]-tri[k][0])*(y-tri[k][1])-(tri[(k+1)%3][1]-tri[k][1])*(x-tri[k][0]) for k in range(3)]
                if all(e >= -1e-6 for e in d) or all(e <= 1e-6 for e in d):
                    pix.add((min(fw-1, int(wrap(x/fw)*fw)), min(fh-1, int(wrap(y/fh)*fh))))
    return pix

derived = flower.copy()
stems = uv_pixels(mesh('season08_normals', 'flw_cosmos_x')['vertices'])
def recolor(source, hue, sat_scale, val_scale):
    for px, py in uv_pixels(mesh("season08_normals", source)["vertices"]):
        r, g, b, a = flower.getpixel((px, py))
        h, s, v = colorsys.rgb_to_hsv(r/255, g/255, b/255)
        if a == 0 or (.17 < h < .45 and s > .2): continue  # leave green stem/leaf texels
        if source.endswith('_wt'): s = max(s, .55*v)
        nr, ng, nb = colorsys.hsv_to_rgb(hue, min(1, s*sat_scale), min(1, v*val_scale))
        derived.putpixel((px, py), (round(nr*255), round(ng*255), round(nb*255), a))
recolor('flw_cosmos_pi', .78, 1.0, .95)   # purple from the original pink cosmos
recolor('flw_cosmos_wt', .62, 1.0, .95)   # blue from the original white cosmos
array('pc_flower_tex', gx_rgba8(flower))
array('pc_flower_derived_tex', gx_rgba8(derived))
derived.save(SRC/"flower_cosmos_derived.png"); print("recolored texels", sum(1 for p,q in zip(flower.getdata(), derived.getdata()) if p!=q))

# kind: 0..2 weeds A/B/C; 3..11 native flower order; 12..14 growing stems.
models = [('fg_grassA', 'weed'), ('fg_grassB', 'weed'), ('fg_grassC', 'weed'),
          ('flw_pansy_wt', 'flower'), ('flw_pansy_vi', 'flower'), ('flw_pansy_ye', 'flower'),
          ('flw_cosmos_ye', 'flower'), ('flw_cosmos_pi', 'derived'), ('flw_cosmos_wt', 'derived'),
          ('flw_tulip_rd', 'flower'), ('flw_tulip_wt', 'flower'), ('flw_tulip_ye', 'flower'),
          ('flw_pansy_x', 'flower'), ('flw_cosmos_x', 'flower'), ('flw_tulip_x', 'flower')]
counts = []
for kind, (name, atlas) in enumerate(models):
    vs = mesh('season08_normals', name)['vertices']
    for s in range(23): assert mesh(f'season{s:02}_normals', name)['vertices'] == vs, (name, s)
    w, h = bush_size if atlas == 'weed' else (fw, fh)
    image = {'weed': 'pc_weed_season00_tex', 'flower': 'pc_flower_tex', 'derived': 'pc_flower_derived_tex'}[atlas]
    counts.append(len(vs))
    out.append(f'static const PC_TreeSourceLight pc_gp_{kind}_light[] = {{')
    for v in vs:
        n = v['normal']; length = sum(c*c for c in n)**.5 or 1
        out.append('{{%s},{%s}},' % (','.join('%.8ff' % (c/length) for c in n), ','.join(str((v['color'] >> b) & 255) for b in (16, 8, 0, 24))))
    out.append('};')
    out.append(f'static Vtx pc_gp_{kind}_v[] ATTRIBUTE_ALIGN(32) = {{')
    for v in vs:
        x, y, z = [round(c*SCALE) for c in v['position']]
        u, t = v['uv']; u = round(u*w*32); t = round((1-t)*h*32)
        out.append('{{{%d,%d,%d},1,{%d,%d},{%s}}},' % (x, y, z, u, t, ','.join(str((v['color'] >> s) & 255) for s in (16, 8, 0, 24))))
    out += ['};', f'static Gfx pc_gp_{kind}_dl[] = {{', 'gsDPPipeSync(),', 'gsSPTexture(0,0,0,G_TX_RENDERTILE,G_ON),',
            'gsDPSetTexEdgeAlpha(78),', 'gsDPSetCombineLERP(TEXEL0,0,SHADE,0,0,0,0,TEXEL0,PRIMITIVE,0,COMBINED,0,0,0,0,COMBINED),',
            f'gsDPSetTextureImage_Dolphin(G_IM_FMT_RGBA,G_IM_SIZ_32b,{w},{h},{image}),',
            'gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE,0,0,GX_MIRROR,GX_MIRROR,0,0),',
            'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_FOG|G_SHADING_SMOOTH|G_DECAL_LEQUAL),',
            'gsDPSetRenderMode(G_RM_FOG_SHADE_A,G_RM_AA_ZB_TEX_EDGE2),']
    for base in range(0, len(vs), 30):
        count = min(30, len(vs)-base)
        out.append(f'gsSPVertex(&pc_gp_{kind}_v[{base}],{count},0),')
        idx = list(range(count)); out.append('gsSPNTrianglesInit_5b(%d,%s),' % (count//3, ','.join(map(str, (idx+[0]*9)[:9]))))
        for i in range(9, count, 12): out.append('gsSPNTriangles_5b(%s),' % ','.join(map(str, (idx[i:i+12]+[0]*12)[:12])))
    out += ['gsDPPipeSync(),', 'gsDPSetTexEdgeAlpha(144),',
            'gsSPLoadGeometryMode(G_ZBUFFER|G_SHADE|G_CULL_BACK|G_FOG|G_LIGHTING|G_SHADING_SMOOTH|G_DECAL_LEQUAL),',
            'gsSPEndDisplayList(),', '};']
N = len(models)
out += ['Gfx* pc_ground_plant_mesh(int kind) {',
        'static Gfx* lists[]={'+','.join(f'pc_gp_{i}_dl' for i in range(N))+'};',
        'static Vtx* vertices[]={'+','.join(f'pc_gp_{i}_v' for i in range(N))+'};',
        'static const PC_TreeSourceLight* source[]={'+','.join(f'pc_gp_{i}_light' for i in range(N))+'};',
        'static const int counts[]={'+','.join(map(str, counts))+'};', f'static unsigned generations[{N}];',
        f'if(kind<0 || kind>={N}) return NULL;',
        'if(generations[kind]!=pc_tree_light_generation) { pc_tree_light_vertices(vertices[kind],source[kind],counts[kind]); generations[kind]=pc_tree_light_generation; }',
        '/* Entry 4 is the image command; weeds follow the original tree calendar. */',
        'if(kind<3) lists[kind][4].words.w1=_GBI_RUNTIME_PTR(pc_weed_atlases[pc_tree_world_season()]);',
        'return lists[kind];', '}']
(ROOT/'ACGC-PC-Port/pc/src/pc_ground_plants.c_inc').write_text('\n'.join(out)+'\n')
print('ground plant kinds', N, 'weed atlases', len(seen), 'flower atlas', flower.size)
